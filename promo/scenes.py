# Как произносить (в субтитрах — как написано): латиница и имена для синтеза.
SAY = {"OBS": "О-Би-Эс", "Gemini": "Джемини", "Macan": "Макан", "YouTube": "ютубе", "Telegram": "телеграма"}


def spoken(text: str) -> str:
    for k, v in SAY.items():
        text = text.replace(k, v)
    return text
