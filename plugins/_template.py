"""
Образец плагина. Скопируйте файл, переименуйте (без подчёркивания в начале),
заполните PLUGIN и run() — больше ничего менять не нужно.

Реестр (core/action_loader.py) найдёт плагин при запуске сам: ни списка в
main.py, ни ветки в диспетчере для него не требуется.

Что важно знать:

  • Имя должно быть латиницей: ^[a-zA-Z_][a-zA-Z0-9_]{0,63}$ — так требует
    Gemini, и плагин с русским именем будет отклонён с записью в лог.

  • Описание читает МОДЕЛЬ, а не человек. Пишите в нём, КОГДА вызывать
    инструмент и какими словами человек об этом просит. Если ваш плагин можно
    спутать с существующим — скажите прямо, какой брать вместо него.

  • Возвращайте короткую фразу: её произнесут вслух. Без markdown, без списков
    и без таблиц.

  • Не бросайте исключений: ловите свои ошибки и возвращайте строку с
    объяснением. Реестр перехватит и падение, но полагаться на это не стоит —
    ваш текст ошибки человеку понятнее нашего.

  • Плагин можно выключить, не удаляя файл: `"plugins_disabled": ["имя"]`
    в config/api_keys.json.
"""

import logging

_logger = logging.getLogger(__name__)


def run(parameters: dict, player=None) -> str:
    """
    parameters — то, что модель разобрала из речи, по схеме из PLUGIN.
    player — окно ДЖАРВИСА. `player.write_log("...")` пишет строку в панель
             диалога. Может быть None (запуск без окна) — проверяйте.
    """
    что = str((parameters or {}).get("example_arg", "")).strip()
    try:
        результат = f"Сделал что просили: {что}" if что else "Сделал."
    except Exception as exc:
        _logger.warning("Плагин-образец сорвался: %s", exc)
        return f"Плагин не сработал, сэр: {exc}"

    if player:
        try:
            player.write_log(f"PLUGIN: {результат}")
        except Exception:
            pass
    return результат


PLUGIN = {
    "name": "my_plugin",
    "description": (
        "Одно-два предложения о том, когда вызывать этот инструмент. "
        "Назовите слова, которыми человек об этом просит."
    ),
    "parameters": {
        "type": "OBJECT",
        "properties": {
            "example_arg": {"type": "STRING", "description": "Что означает этот аргумент"},
        },
        "required": [],
    },
    "handler": run,
}
