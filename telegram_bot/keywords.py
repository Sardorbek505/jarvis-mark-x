"""Поиск ключевых слов по началу слова, а не произвольной подстрокой.

Зачем: подстрочный поиск однажды превратил личное сообщение в команду ПК.
20.06.2026 на фразу «…высокий накаченный обеспеченный и чистоплотный…»
Джарвис ответил «🖥 Готово» — потому что «чиСТОПлотный» содержит «стоп».
Пользователь переспросил «Че готова?», а модель, не понимая, о чём речь,
сочинила объяснение про сохранение в память.

Почему именно префикс, а не полное слово: русская морфология. Ключ «камер»
обязан ловить «камеру», «камерой», «камеры» — но не «скамерами» и не
середину чужого слова.
"""
import re
from functools import lru_cache
from typing import Iterable


@lru_cache(maxsize=64)
def _compile(keys: tuple[str, ...]) -> re.Pattern:
    # (?<!\w) — ключ обязан начинаться на границе слова; конец свободен,
    # чтобы работали окончания.
    return re.compile(
        r"(?<!\w)(?:" + "|".join(re.escape(k) for k in keys) + r")",
        re.IGNORECASE,
    )


def matches(text: str, keys: Iterable[str]) -> bool:
    """Есть ли в тексте слово, начинающееся с одного из ключей."""
    if not text:
        return False
    return _compile(tuple(keys)).search(text) is not None
