"""Характер Джарвиса не должен расползаться.

Реплики живут в семи местах сразу — в промпте и в шести модулях, где они
захардкожены. Промпт можно переписать сколько угодно раз: если строка зашита
в Python, Джарвис всё равно скажет её. Так и было: после правки характера в
`core/prompt.txt` движок инициативы продолжал выдавать «Сэр, чем могу
помочь?», и нашёл это не глаз, а сквозной прогон голосового круга.

Здесь запрещённые обороты проверяются автоматически. Список — из раздела
«Чем ты не являешься» в `core/prompt.txt`; при правке характера меняются оба
места сразу.
"""

import re
import sys
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

# Файлы, где живут произносимые реплики. Промпт сюда не входит: в нём эти же
# обороты перечислены как ЗАПРЕЩЁННЫЕ, и запрет на запрет был бы абсурдом.
ГОВОРЯЩИЕ_ФАЙЛЫ = [
    "core/initiative_engine.py",
    "core/proactive_engine.py",
    "core/emotion_analyzer.py",
    "core/smart_reminders.py",
    "actions/modes.py",
    "actions/morning_briefing.py",
]

# (шаблон, чем плохо) — регистр не учитывается
ЗАПРЕЩЕНО = [
    (r"чем могу помочь", "реплика колл-центра, не дворецкого"),
    (r"рад стараться", "заискивание"),
    (r"всегда пожалуйста", "заискивание"),
    (r"я вижу,? вам\b", "диагноз в лицо вместо действия"),
    (r"я вижу,? вы\b", "диагноз в лицо вместо действия"),
    (r"вы выглядите", "диагноз в лицо вместо действия"),
    (r"мне кажется,? вам", "диагноз в лицо вместо действия"),
    (r"хочу поднять вам настроение", "навязчивая забота"),
    (r"\bура\b", "восклицание не в характере"),
    (r"отлично!", "восклицание не в характере"),
    (r"замечательно!", "восклицание не в характере"),
    (r"прекрасно!", "восклицание не в характере"),
    (r"я всего лишь", "самоуничижение"),
    (r"как ИИ,? я", "самоуничижение"),
    (r"отличный вопрос", "лесть"),
    # Грамматика речи (раздел «Грамматика речи» в core/prompt.txt).
    (r"извините", "Джарвис не извиняется: неудача — факт о мире"),
    (r"прошу прощения", "Джарвис не извиняется: неудача — факт о мире"),
    (r"сожалею", "Джарвис не извиняется: неудача — факт о мире"),
    (r"чем ещё могу", "реплика колл-центра, не дворецкого"),
    (r"как я (уже )?(говорил|сказал)", "возврат к прерванной мысли"),
    (r"вот что я (нашёл|нашел)", "успех должен быть безличным"),
    (r"я закончил", "успех должен быть безличным"),
]

# Про слова срочности («срочно», «немедленно», «критично») тест молчит
# СОЗНАТЕЛЬНО. В промпте они запрещены, но в коде те же слова живут как
# ключи поиска: `smart_reminders` по ним отличает важное напоминание от
# обычного. Запрет на произнесение и запрет на упоминание — разные вещи, и
# механически их здесь не различить.


def _строки_кода(path: Path):
    """Строки, которые Джарвис действительно может произнести.

    Пропускаем комментарии (там запрет упоминать можно) и демо-блок
    `if __name__ == "__main__":` — в нём лежат примеры реплик ПОЛЬЗОВАТЕЛЯ,
    и «Всё отлично!» там совершенно уместно.
    """
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith("#"):
            continue
        if re.match(r'\s*if\s+__name__\s*==', line):
            return
        yield n, line


@pytest.mark.parametrize("отн_путь", ГОВОРЯЩИЕ_ФАЙЛЫ)
def test_в_репликах_нет_запрещённых_оборотов(отн_путь):
    path = _BASE / отн_путь
    assert path.exists(), f"{отн_путь} пропал — список говорящих файлов устарел"

    находки = []
    for n, line in _строки_кода(path):
        for шаблон, причина in ЗАПРЕЩЕНО:
            if re.search(шаблон, line, re.IGNORECASE):
                находки.append(f"{отн_путь}:{n}: «{line.strip()[:70]}» — {причина}")

    assert not находки, "характер разъехался:\n" + "\n".join(находки)


def test_промпт_держит_спецификацию_характера():
    """Если раздел вырезали, тесты выше проверяют пустоту."""
