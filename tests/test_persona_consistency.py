def test_бот_и_голос_держат_один_характер():
    """У Telegram-бота свой системный промпт — и он тоже должен быть каноном.

    Память и промпты у голоса и у бота раздельные (проверено: перекрёстных
    импортов ноль), так что разъехаться они могут независимо.
    """
    бот = (_BASE / "telegram_bot" / "gemini_client.py").read_text(encoding="utf-8")
    for якорь in ("Невозмутимость", "Сухая ирония", "Возражение ровно один раз",
                  "ЧЕМ ТЫ НЕ ЯВЛЯЕШЬСЯ", "Обращение — «сэр»"):
        assert якорь in бот, f"в промпте бота пропало: «{якорь}»"


def test_режимы_личности_остались_нетронутыми():
    """«Друг» и «Наставник» ломают канон намеренно — это фича, не дефект."""
    from telegram_bot import personas

    assert personas.PERSONAS["normal"]["overlay"] == "", \
        "«Обычный» обязан быть чистым каноном, без наложений"
    assert "на «ты»" in personas.PERSONAS["friend"]["overlay"], \
        "режим «Друг» потерял неформальность — его не надо чинить под канон"


def test_обращение_сэр_осталось_основным():
    """«Сэр» — константа характера; без него это уже не Джарвис."""
    from core import initiative_engine

    engine = initiative_engine.InitiativeEngine()
    реплики = []
    for эмоция in ("sad", "bored", "stressed", "tired", "happy"):
        реплика = engine._generate_initiative(
            {"emotion": эмоция, "confidence": 0.9}, {"preferences": {}}
        )
        if реплика:
            реплики.append(реплика)

    assert реплики, "движок инициативы не выдал ни одной реплики"
    без_обращения = [r for r in реплики if "сэр" not in r.lower()]
    assert not без_обращения, f"реплики без обращения: {без_обращения}"


