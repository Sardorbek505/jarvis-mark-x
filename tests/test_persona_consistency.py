def test_грамматика_речи_на_месте_целиком():
    """Восемь правил — это спецификация, а не украшение. Половина из них
    описывает то, чего в речи быть НЕ должно, и вырезать любое значит
    молча разрешить запрещённое."""
    prompt = (_BASE / "core" / "prompt.txt").read_text(encoding="utf-8")
    раздел = prompt[prompt.index("## Грамматика речи"):]
    раздел = раздел[:раздел.index("## Чем ты не являешься")]

    for правило in ("«Сэр» — это позиция", "Срочность передаётся удалением",
                    "Успех безличен", "Неудача — факт о мире",
                    "Хорошее первым", "восстанавливай его в ответе",
                    "не повторяй его", "не возвращайся к прерванной мысли"):
        assert правило in раздел, f"из грамматики речи пропало правило «{правило}»"


def test_правило_про_обрыв_согласовано_с_кодом():
    """Правило 8 появилось потому, что перебивание теперь есть на самом
    деле. Если механизм уберут, а правило останется, промпт будет описывать
    несуществующее поведение."""
    prompt = (_BASE / "core" / "prompt.txt").read_text(encoding="utf-8")
    assert "перебить, назвав по имени" in prompt

    барж = (_BASE / "core" / "barge_in.py")
    assert барж.exists(), "правило в промпте есть, а механизма обрыва нет"


def test_запреты_грамматики_проверяются_механически():
    """Правило, которое нельзя проверить, через полгода становится
    пожеланием. Каждый запрет из грамматики речи, поддающийся проверке,
    должен лежать в списке ЗАПРЕЩЕНО."""
    шаблоны = " ".join(ш for ш, _ in ЗАПРЕЩЕНО)

    assert "извините" in шаблоны
    assert "прощения" in шаблоны
    assert "как я" in шаблоны
    assert "я закончил" in шаблоны
