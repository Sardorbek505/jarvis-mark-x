"""Промах мышью — это не «не сработало», это нажатая соседняя кнопка.

«Нажми Сохранить» — просьба, которую человек произносит естественно и которую
нельзя было выполнить: мышью Джарвис не владел, а координаты голосом не
диктуют. Теперь снимок экрана уходит в модель зрения, та возвращает рамку
элемента, по рамке считается середина.

Между «Сохранить» и «Удалить» на панели пара сантиметров, и цена ошибки
несимметрична настолько, что бóльшая часть этих тестов — про отказ нажимать.
"""

import sys
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

from actions import screen_pointer as sp


class _Окно:
    def __init__(self):
        self.лог: list[str] = []

    def write_log(self, текст):
        self.лог.append(текст)


@pytest.fixture
def экран(monkeypatch):
    """Зрение, отвечающее что велено, и мышь, запоминающая движения."""
    состояние = {"ответ": None, "движения": [], "клики": []}

    monkeypatch.setattr(sp, "_спросить_зрение",
                        lambda запрос: состояние["ответ"])

    class _Мышь:
        @staticmethod
        def moveTo(x, y, duration=0):
            состояние["движения"].append((x, y))

        @staticmethod
        def click(button="left"):
            состояние["клики"].append(button)

        @staticmethod
        def doubleClick():
            состояние["клики"].append("double")

        @staticmethod
        def scroll(шагов):
            состояние["клики"].append(("scroll", шагов))

    monkeypatch.setattr(sp, "_мышь", lambda: _Мышь)
    return состояние


def _нашлось(label="Сохранить", confidence="высокая", box=(400, 200, 440, 300)):
    return {"found": True, "box": list(box), "label": label,
            "confidence": confidence, "_ширина": 1000, "_высота": 1000}


# ─── Когда нажимать нельзя ───────────────────────────────────────────────────

def test_ненайденное_не_нажимается(экран):
    экран["ответ"] = {"found": False, "_ширина": 1000, "_высота": 1000}

    ответ = sp.screen_pointer({"action": "click", "target": "кнопка Сохранить"})

    assert экран["клики"] == []
    assert "не вижу" in ответ


def test_низкая_уверенность_останавливает_клик(экран):
    """Модель сама сказала, что подходящих элементов несколько. Нажать
    наугад — значит выбрать монеткой между «Сохранить» и «Сохранить как»."""
    экран["ответ"] = _нашлось(confidence="низкая")

    ответ = sp.screen_pointer({"action": "click", "target": "Сохранить"})

    assert экран["клики"] == []
    assert экран["движения"] == []
    assert "не уверен" in ответ


def test_чужая_надпись_останавливает_клик(экран):
    """Модель нашла «что-то похожее по смыслу». Нажимать по смыслу нельзя."""
    экран["ответ"] = _нашлось(label="Удалить")

    ответ = sp.screen_pointer({"action": "click", "target": "Сохранить"})

    assert экран["клики"] == []
    assert "Удалить" in ответ


def test_отказ_называет_координаты_а_не_просто_отказывает(экран):
    """Человеку нужно понять, что Джарвис вообще увидел."""
    экран["ответ"] = _нашлось(confidence="низкая")

    ответ = sp.screen_pointer({"action": "click", "target": "Сохранить"})

    assert "250" in ответ and "420" in ответ


def test_кривая_рамка_не_приводит_к_клику(экран):
    экран["ответ"] = {"found": True, "box": ["левее", "выше"], "label": "Кнопка",
                      "confidence": "высокая", "_ширина": 1000, "_высота": 1000}

    ответ = sp.screen_pointer({"action": "click", "target": "кнопка"})

    assert экран["клики"] == []
    assert "не понял где" in ответ


def test_рамка_за_краем_экрана_отвергается(экран):
    """Модель иногда возвращает координаты не в той шкале. Клик по точке
    вне экрана в лучшем случае ничего не сделает."""
    экран["ответ"] = _нашлось(box=(5000, 5000, 6000, 6000))

    ответ = sp.screen_pointer({"action": "click", "target": "кнопка"})

    assert экран["клики"] == []


def test_недоступное_зрение_не_выдаётся_за_отсутствие_кнопки(экран):
    """«Не вижу такой кнопки» и «не смог посмотреть» — разные новости."""
    экран["ответ"] = None

    ответ = sp.screen_pointer({"action": "click", "target": "Сохранить"})

    assert "зрение недоступно" in ответ


# ─── Когда нажимать можно ────────────────────────────────────────────────────

def test_уверенная_находка_нажимается(экран):
    экран["ответ"] = _нашлось()
    окно = _Окно()

    ответ = sp.screen_pointer(
        {"action": "click", "target": "кнопка Сохранить"}, player=окно)

    assert экран["клики"] == ["left"]
    assert экран["движения"] == [(250, 420)]
    assert "Сохранил" not in ответ           # нажал, а не сохранил
    assert "Нажал" in ответ
    assert окно.лог


def test_поиск_наводит_курсор_но_не_нажимает(экран):
    """`find` — безопасное действие: посмотреть, где это, ничего не трогая."""
    экран["ответ"] = _нашлось()

    ответ = sp.screen_pointer({"action": "find", "target": "Сохранить"})

    assert экран["клики"] == []
    assert экран["движения"] == [(250, 420)]
    assert "Навёл" in ответ


def test_поиск_работает_и_при_низкой_уверенности(экран):
    """Отказ нужен перед нажатием, а не перед взглядом."""
    экран["ответ"] = _нашлось(confidence="низкая")

    ответ = sp.screen_pointer({"action": "find", "target": "Сохранить"})

    assert экран["движения"] == [(250, 420)]
    assert "Навёл" in ответ


def test_двойной_и_правый_клик_различаются(экран):
    экран["ответ"] = _нашлось(label="Файл")

    sp.screen_pointer({"action": "double_click", "target": "Файл"})
    sp.screen_pointer({"action": "right_click", "target": "Файл"})

    assert экран["клики"] == ["double", "right"]


def test_середина_рамки_считается_по_настоящему_размеру():
    """Модель отвечает в шкале 0-1000, а экран у человека любой."""
    assert sp._середина([0, 0, 1000, 1000], 1920, 1080) == (960, 540)
    assert sp._середина([500, 500, 500, 500], 1920, 1080) == (960, 540)


# ─── Прокрутка ───────────────────────────────────────────────────────────────

def test_прокрутка_вниз_и_вверх_различаются(экран):
    sp.screen_pointer({"action": "scroll", "direction": "down", "amount": 2})
    sp.screen_pointer({"action": "scroll", "direction": "up", "amount": 2})

    вниз, вверх = экран["клики"]
    assert вниз[1] < 0 < вверх[1]


def test_нечисловая_прокрутка_не_роняет_инструмент(экран):
    sp.screen_pointer({"action": "scroll", "amount": "немного"})
    assert экран["клики"]


