def test_отсутствие_мыши_объясняется(monkeypatch, экран):
    экран["ответ"] = _нашлось()
    monkeypatch.setattr(sp, "_мышь", lambda: None)

    ответ = sp.screen_pointer({"action": "click", "target": "Сохранить"})

    assert "pyautogui" in ответ


