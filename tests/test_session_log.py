"""«Вчера мы говорили о…» — то, по чему видно, что перед тобой не машина.

Долгосрочная память хранит ФАКТЫ: как зовут, где живёт, что любит. Разговор
она не хранила вовсе, и каждое утро Джарвис начинал с чистого листа — при том,
что накануне вечером обсуждали переезд.

Проверяется дешёвая запись, ленивая выжимка и — отдельно — то, что пустота
здесь нормальна: в первый день, после молчаливой недели, после разговора из
двух реплик брифинг обязан выглядеть целым и без этой строки.
"""

import json
import sys
from datetime import date, timedelta
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

from core import session_log as sl


@pytest.fixture
def журнал(tmp_path, monkeypatch):
    monkeypatch.setattr(sl, "_папка", lambda: tmp_path)
    return tmp_path


@pytest.fixture
def модель(monkeypatch):
    """Текстовая модель, отвечающая что велено."""
    состояние = {"ответ": "обсуждали переезд и не нашли грузчиков",
                 "спрошено": []}

    from core import llm_client

    def _ask(запрос, **kwargs):
        состояние["спрошено"].append(запрос)
        return состояние["ответ"]

    monkeypatch.setattr(llm_client, "ask", _ask)
    return состояние


def _наговорить(день: date, сколько: int = 6):
    for i in range(сколько):
        sl.remember("Вы", f"реплика человека номер {i}", когда=день)
        sl.remember("Джарвис", f"ответ ассистента номер {i}", когда=день)


# ─── Запись ──────────────────────────────────────────────────────────────────

def test_реплики_дописываются_в_файл_дня(журнал):
    sl.remember("Вы", "найди билеты в Ташкент")
    sl.remember("Джарвис", "нашёл три рейса")

    строки = (журнал / f"{date.today().isoformat()}.jsonl").read_text(
        encoding="utf-8").strip().splitlines()

    assert len(строки) == 2
    assert json.loads(строки[0])["текст"] == "найди билеты в Ташкент"


def test_междометия_не_пишутся(журнал):
    """«Да», «ага», «ок» — это не то, о чём вспоминают наутро."""
    for звук in ("да", "ага", "ок", "  "):
        sl.remember("Вы", звук)

    assert not list(журнал.glob("*.jsonl"))


def test_сорванная_запись_ничего_не_роняет(журнал, monkeypatch):
    """Журнал разговоров — удобство. Он не имеет права уронить голосовой ход."""
    monkeypatch.setattr(sl, "_файл",
                        lambda день: (_ for _ in ()).throw(OSError("диск полон")))

    sl.remember("Вы", "что-нибудь длинное")   # не должно поднять исключение


def test_оборванная_строка_не_ломает_чтение(журнал):
    """Аварийное закрытие оставляет недописанную строку."""
    файл = журнал / f"{date.today().isoformat()}.jsonl"
    файл.write_text('{"кто":"Вы","текст":"целая"}\n{"кто":"Вы","те',
                    encoding="utf-8")

    assert len(sl._прочитать(date.today())) == 1


# ─── Какой день считается прошлым ────────────────────────────────────────────

def test_прошлым_считается_последний_разговор_а_не_вчерашний_день(журнал):
    """Между разговорами бывают выходные. «Вчера мы говорили» про день,
    когда компьютер не включали, звучало бы ложью."""
    давно = date.today() - timedelta(days=4)
    _наговорить(давно)

    assert sl.прошлый_день() == давно


