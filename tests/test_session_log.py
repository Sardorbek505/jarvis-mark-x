# ─── Выжимка ─────────────────────────────────────────────────────────────────

def test_выжимка_считается_один_раз(журнал, модель):
    """Один вызов модели в сутки вместо одного на каждую реплику — ради
    этого запись и сделана дешёвой, а выжимка ленивой."""
    вчера = date.today() - timedelta(days=1)
    _наговорить(вчера)

    первая = sl.выжимка(вчера)
    вторая = sl.выжимка(вчера)

    assert первая == вторая == "обсуждали переезд и не нашли грузчиков"
    assert len(модель["спрошено"]) == 1


def test_короткий_разговор_не_вспоминается(журнал, модель):
    """Две реплики и «спасибо» — не разговор, и начинать с него день значит
    начинать с пустого места."""
    вчера = date.today() - timedelta(days=1)
    sl.remember("Вы", "который час", когда=вчера)
    sl.remember("Джарвис", "половина седьмого", когда=вчера)

    assert sl.выжимка(вчера) == ""
    assert модель["спрошено"] == []


def test_модель_сказавшая_нет_не_попадает_в_брифинг(журнал, модель):
    """Ей велено отвечать «нет», когда говорить не о чем, — и это не текст
    для произнесения вслух."""
    вчера = date.today() - timedelta(days=1)
    _наговорить(вчера)
    модель["ответ"] = "Нет."

    assert sl.выжимка(вчера) == ""


def test_молчащая_модель_не_ломает_вспоминание(журнал, модель):
    вчера = date.today() - timedelta(days=1)
    _наговорить(вчера)
    модель["ответ"] = ""

    assert sl.выжимка(вчера) == ""


def test_модели_отдаётся_хвост_разговора(журнал, модель, monkeypatch):
    """Конец разговора обычно важнее его завязки."""
    monkeypatch.setattr(sl, "_ПРЕДЕЛ_РАСШИФРОВКИ", 120)
    вчера = date.today() - timedelta(days=1)
    _наговорить(вчера, сколько=40)

    sl.выжимка(вчера)

    отданное = модель["спрошено"][0]
    assert len(отданное) <= 120
    assert "номер 39" in отданное


# ─── Уборка ──────────────────────────────────────────────────────────────────

def test_старые_журналы_удаляются(журнал, модель):
    """Расшифровка разговоров — не то, что стоит копить бесконечно."""
    старьё = date.today() - timedelta(days=sl.ХРАНИМ_ДНЕЙ + 3)
    свежее = date.today() - timedelta(days=2)
    _наговорить(старьё)
    _наговорить(свежее)

    sl.подчистить()

    остались = {п.stem for п in журнал.glob("*.jsonl")}
    assert остались == {свежее.isoformat()}


def test_выжимка_старого_дня_тоже_удаляется(журнал, модель):
    старьё = date.today() - timedelta(days=sl.ХРАНИМ_ДНЕЙ + 3)
    _наговорить(старьё)
    (журнал / f"{старьё.isoformat()}.summary.txt").write_text("о чём-то",
                                                              encoding="utf-8")

    sl.подчистить()

    assert not list(журнал.glob(f"{старьё.isoformat()}*"))


def test_посторонние_файлы_не_трогаются(журнал):
    (журнал / "заметка.txt").write_text("не журнал", encoding="utf-8")
    sl.подчистить()
    assert (журнал / "заметка.txt").exists()


