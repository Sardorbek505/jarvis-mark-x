"""Написать человеку — но не отправить за него.

Соблазн дожать последний шаг велик: в `wa.me` после загрузки достаточно
послать Enter. Но проверить, что чат открылся, что открылся ТОТ чат и что
фокус стоит в поле ввода, нечем. Цена ошибки несимметрична: неотправленное
сообщение человек отправит сам за секунду, отправленное не тому не
отзывается никак.

Поэтому здесь проверяется в первую очередь, чего инструмент НЕ делает: не
отправляет, не обещает отправленного и не угадывает номер.
"""

import json
import sys
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

from actions import messenger as ms


@pytest.fixture
def книжка(tmp_path, monkeypatch):
    файл = tmp_path / "contacts.json"
    monkeypatch.setattr(ms, "_файл", lambda: файл)
    return файл


@pytest.fixture
def открытое(monkeypatch):
    ссылки = []
    monkeypatch.setattr(ms, "_открыть", ссылки.append)
    return ссылки


# ─── Чего инструмент не делает ───────────────────────────────────────────────

def test_сообщение_не_отправляется_а_готовится(книжка, открытое):
    ответ = ms.messenger({"to": "+7 999 123-45-67", "text": "буду через час"})

    assert "нажмите отправку" in ответ.lower()
    for обещание in ("отправил", "отправлено", "послал"):
        assert обещание not in ответ.lower(), f"ответ обещает «{обещание}»"


def test_короткий_номер_отклоняется(книжка, открытое):
    """Из десяти цифр без кода страны нельзя понять, российский это номер
    или узбекский. Угадать — значит написать постороннему человеку."""
    ответ = ms.messenger({"to": "9991234567", "text": "привет"})

    assert открытое == []
    assert "код" in ответ.lower()


def test_неизвестное_имя_не_превращается_в_номер(книжка, открытое):
    ответ = ms.messenger({"to": "мама", "text": "буду через час"})

    assert открытое == []
    assert "не знаю номера" in ответ.lower()


def test_пустой_текст_не_открывает_переписку(книжка, открытое):
    assert открытое == []
    ms.messenger({"to": "+79991234567", "text": ""})
    assert открытое == []


# ─── Номер ───────────────────────────────────────────────────────────────────

def test_привычная_восьмёрка_становится_кодом_страны():
    """«8 (999) 123-45-67» пишут все, и другого прочтения у такой записи нет."""
    assert ms._номер("8 (999) 123-45-67")[0] == "79991234567"


def test_номер_собирается_из_любой_записи():
    for запись in ("+7 999 123 45 67", "+7(999)123-45-67", "7 999 1234567"):
        assert ms._номер(запись)[0] == "79991234567", запись


def test_международный_номер_остаётся_как_есть():
    assert ms._номер("+998 90 123 45 67")[0] == "998901234567"


def test_слишком_длинное_не_номер():
    assert ms._номер("1234567890123456789")[0] is None


def test_использованный_номер_называется_вслух(книжка, открытое):
    """Единственная догадка в этом коде должна быть видна сразу, а не
    обнаружиться по ответу постороннего человека."""
    ответ = ms.messenger({"to": "8 999 123-45-67", "text": "привет"})
    assert "+79991234567" in ответ


# ─── Куда и с чем открывается ────────────────────────────────────────────────

def test_ватсап_открывается_ссылкой_с_текстом(книжка, открытое):
    ms.messenger({"to": "+79991234567", "text": "буду через час"})

    assert открытое[0].startswith("https://wa.me/79991234567?text=")
    assert "%D1%87%D0%B0%D1%81" in открытое[0]      # «час» в кодировке URL


def test_телеграм_открывается_своей_схемой(книжка, открытое):
    """Веб-версия по ссылке текст не подставляет — именно поэтому tg://."""
    ms.messenger({"to": "+79991234567", "text": "привет", "app": "telegram"})

    assert открытое[0].startswith("tg://resolve?phone=79991234567&text=")


@pytest.mark.parametrize("как_сказали", ["ватсап", "вотсап", "WhatsApp", "вацап"])
def test_приложение_узнаётся_по_живому_названию(как_сказали):
    assert ms._приложение(как_сказали) == "whatsapp"


@pytest.mark.parametrize("как_сказали", ["телеграм", "Telegram", "телега"])
def test_телеграм_тоже_узнаётся(как_сказали):
    assert ms._приложение(как_сказали) == "telegram"


def test_без_названия_пишем_в_ватсап():
    assert ms._приложение("") == "whatsapp"


# ─── Записная книжка ─────────────────────────────────────────────────────────

def test_номер_запоминается_и_дальше_хватает_имени(книжка, открытое):
    """Голосом номер не диктуют — говорят «напиши маме»."""
    ms.messenger({"action": "save_contact", "to": "мама", "phone": "8 999 123-45-67"})

    ответ = ms.messenger({"to": "маме", "text": "буду через час"})

    assert открытое[0].startswith("https://wa.me/79991234567")
    assert "мама" in ответ


def test_замена_номера_говорится_вслух(книжка):
    """Тихая замена означала бы, что сообщения уходят на новый номер, а
    человек об этом не знает."""
    ms.messenger({"action": "save_contact", "to": "Дима", "phone": "+79990000000"})
    ответ = ms.messenger({"action": "save_contact", "to": "Дима", "phone": "+79991111111"})

    assert "было" in ответ and "стало" in ответ


def test_кривой_номер_в_книжку_не_попадает(книжка):
    ответ = ms.messenger({"action": "save_contact", "to": "Дима", "phone": "12345"})

    assert ms._контакты() == {}
    assert "код" in ответ.lower()


def test_падежное_окончание_не_мешает_найти(книжка):
    """Говорят «напиши МАМЕ» и «скинь ДИМЕ», а записано «мама» и «Дима»."""
    ms.messenger({"action": "save_contact", "to": "мама", "phone": "+79991234567"})
    assert ms._найти_контакт("маме")[0] == "мама"
    assert ms._найти_контакт("маму")[0] == "мама"


def test_похожие_имена_не_путаются(книжка):
    """«Дима» и «Дина» похожи ровно настолько же, насколько «Дима» и «Диме».
    Нечёткое сравнение выбирало бы между ними монеткой."""
    ms.messenger({"action": "save_contact", "to": "Дима", "phone": "+79991111111"})
    ms.messenger({"action": "save_contact", "to": "Дина", "phone": "+79992222222"})

    assert ms._найти_контакт("Диме")[0] == "Дима"
    assert ms._найти_контакт("Дине")[0] == "Дина"


def test_книжка_перечисляется(книжка):
    ms.messenger({"action": "save_contact", "to": "мама", "phone": "+79991234567"})
    ответ = ms.messenger({"action": "contacts"})
    assert "мама" in ответ and "+79991234567" in ответ


def test_пустая_книжка_подсказывает_что_делать(книжка):
    assert "запиши номер" in ms.messenger({"action": "contacts"})


def test_контакт_убирается(книжка):
    ms.messenger({"action": "save_contact", "to": "мама", "phone": "+79991234567"})
    ms.messenger({"action": "forget_contact", "to": "мама"})
    assert ms._контакты() == {}


def test_книжка_переживает_перезапуск(книжка):
    ms.messenger({"action": "save_contact", "to": "мама", "phone": "+79991234567"})
    assert json.loads(книжка.read_text(encoding="utf-8")) == {"мама": "79991234567"}
