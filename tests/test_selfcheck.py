"""Самопроверка обязана быть безопасной и честной.

Она запускается как раз тогда, когда человек уже не уверен, что всё цело, —
и самопроверка, которая сама что-то испортила, бесполезна вдвойне. Поэтому
проверяется в первую очередь не то, что она находит, а то, чего она НЕ делает
без спроса.
"""

import importlib.util
import sys
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))


def _загрузить():
    """Скрипт лежит в scripts/, а не в пакете — грузим по пути."""
    путь = _BASE / "scripts" / "selfcheck.py"
    спец = importlib.util.spec_from_file_location("_selfcheck", путь)
    модуль = importlib.util.module_from_spec(спец)
    # Зарегистрировать ДО выполнения: `@dataclass` на исполнении ищет модуль
    # класса в sys.modules и падает, не найдя его.
    sys.modules["_selfcheck"] = модуль
    спец.loader.exec_module(модуль)
    return модуль


@pytest.fixture(scope="module")
def sc():
    return _загрузить()


# ─── Устройство ──────────────────────────────────────────────────────────────

def test_проверки_зарегистрированы(sc):
    assert len(sc._проверки) >= 20


def test_имена_не_повторяются(sc):
    пары = [(п.раздел, п.имя) for п in sc._проверки]
    assert len(пары) == len(set(пары))


def test_разделы_идут_подряд(sc):
    """Иначе один раздел напечатается заголовком дважды и отчёт рассыплется."""
    порядок = [п.раздел for п in sc._проверки]
    видели = []
    for раздел in порядок:
        if not видели or видели[-1] != раздел:
            assert раздел not in видели, f"раздел «{раздел}» разорван"
            видели.append(раздел)


# ─── Безопасность ────────────────────────────────────────────────────────────

_МЕНЯЮЩИЕ = {"Движение курсора", "Запись и возврат", "Открыть и закрыть страницу",
             "Поставить и снять задачу"}


def test_всё_меняющее_помечено(sc):
    """Забытая пометка означает, что обычный запуск подвигает человеку мышь
    или сотрёт содержимое буфера."""
    помечено = {п.имя for п in sc._проверки if п.меняет}
    assert помечено == _МЕНЯЮЩИЕ


def test_всё_сетевое_помечено(sc):
    """Запрос в сеть тратит квоту ключа — это должно включаться руками."""
    помечено = {п.имя for п in sc._проверки if п.сеть}
    assert помечено == {"Ответ текстовой модели", "Поиск", "Погода"}


def test_обычный_прогон_не_трогает_меняющее(sc, monkeypatch):
    """Главное свойство: без --полная ни одна меняющая проверка не зовётся."""
    вызвано = []
    for п in sc._проверки:
        if п.меняет or п.сеть:
            monkeypatch.setattr(п, "делать",
                                lambda: вызвано.append(1) or sc.Итог(sc.OK))

    monkeypatch.setattr(sys, "argv", ["selfcheck.py", "--без-цвета"])
    sc.main()

    assert вызвано == []


# ─── Честность отметок ───────────────────────────────────────────────────────

def test_упавшая_проверка_становится_сбоем(sc):
    """Исключение — это тоже ответ, и притом самый важный: значит, в этом
    месте Джарвис свалится молча."""
    п = sc.Проверка("Проба", "взрыв",
                    lambda: (_ for _ in ()).throw(RuntimeError("бум")))

    итог = sc._выполнить(п)

    assert итог.отметка == sc.СБОЙ
    assert "бум" in итог.подробность


def test_болтовня_проверяемого_кода_не_ломает_отчёт(sc, capsys):
    """Мастер ключа, Spotify и драйверы звука печатают своё в stdout."""
    def _болтливая():
        print("Я печатаю прямо в отчёт")
        return sc.Итог(sc.OK, "всё хорошо")

    итог = sc._выполнить(sc.Проверка("Проба", "болтун", _болтливая))

    assert итог.отметка == sc.OK
    assert "печатаю прямо в отчёт" not in capsys.readouterr().out


def test_логи_тоже_приглушены(sc, capsys):
    import logging

    def _тревожная():
        logging.getLogger("проба").error("ТРЕВОГА")
        return sc.Итог(sc.OK)

    sc._выполнить(sc.Проверка("Проба", "тревога", _тревожная))

    захват = capsys.readouterr()
    assert "ТРЕВОГА" not in захват.out + захват.err
    # И приглушение снимается: иначе самопроверка оставила бы весь процесс
    # немым для всех, кто запустил её из кода.
    assert logging.getLogger("проба").isEnabledFor(logging.ERROR)


def test_код_возврата_поднимает_только_сбой(sc, monkeypatch):
    """Отсутствие Steam не должно ронять чужой скрипт, вызвавший
    самопроверку, — а настоящий сбой должен."""
    for п in sc._проверки:
        monkeypatch.setattr(п, "делать", lambda: sc.Итог(sc.НЕТ, "нечем"))
    monkeypatch.setattr(sys, "argv", ["selfcheck.py", "--без-цвета"])
    assert sc.main() == 0

    первая = sc._проверки[0]
    monkeypatch.setattr(первая, "делать", lambda: sc.Итог(sc.СБОЙ, "сломано"))
    assert sc.main() == 1


def test_совет_есть_у_каждого_ожидаемого_отказа(sc, monkeypatch):
    """«НЕТ» без совета оставляет человека с вопросом «и что мне делать».
    Проверяем на настоящем прогоне этой машины."""
    monkeypatch.setattr(sys, "argv", ["selfcheck.py", "--без-цвета"])
    sc.main()   # не должно упасть ни на одной проверке этой машины
