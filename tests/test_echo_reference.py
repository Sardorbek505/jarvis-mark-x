"""Детектор имени не должен ловить самого Джарвиса.

Пока он говорит, микрофон открыт — иначе перебить его было бы нечем. Значит,
в микрофон звучит он сам, из колонок. Без вычитания детектор ловил бы
собственный голос ассистента, и «Джарвис» в его же ответе останавливал бы его.

Опорный сигнал здесь берётся не из WASAPI loopback, а из того, что мы сами
только что отдали в устройство вывода: эти байты известны точно, второй поток
захвата не нужен, и работает это на любой системе.
"""

import sys
from pathlib import Path

import numpy as np
import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

from core.echo_reference import ОпорныйСигнал

_ЧАСТОТА = 16000


def _тон(семплов: int, гц: float = 440.0, громкость: float = 8000.0,
         частота: int = _ЧАСТОТА) -> bytes:
    t = np.arange(семплов) / частота
    return (np.sin(2 * np.pi * гц * t) * громкость).astype(np.int16).tobytes()


@pytest.fixture
def опора():
    return ОпорныйСигнал(частота_микрофона=_ЧАСТОТА)


# ─── Очередь ─────────────────────────────────────────────────────────────────

def test_что_положили_то_и_берут(опора):
    звук = _тон(320)
    опора.положить(звук, _ЧАСТОТА)

    assert опора.взять(320) == звук


def test_очередь_читается_по_порядку(опора):
    """AEC ищет задержку по непрерывному потоку. Отдавать «самый свежий
    кусок» вместо очередного значило бы рвать непрерывность на каждой паузе,
    и выравнивание приходилось бы искать заново."""
    первый, второй = _тон(160, 440.0), _тон(160, 880.0)
    опора.положить(первый, _ЧАСТОТА)
    опора.положить(второй, _ЧАСТОТА)

    assert опора.взять(160) == первый
    assert опора.взять(160) == второй


def test_пустая_очередь_отдаёт_тишину(опора):
    """Тишина в опорном сигнале означает «эха нет» — AEC пропустит кадр
    как есть. Это правильный ответ, когда Джарвис молчит."""
    кусок = опора.взять(160)

    assert len(кусок) == 320
    assert set(кусок) == {0}
    assert опора.отдано_тишины == 1


def test_нехватку_добивают_тишиной(опора):
    опора.положить(_тон(100), _ЧАСТОТА)
    кусок = np.frombuffer(опора.взять(160), dtype=np.int16)

    assert len(кусок) == 160
    assert set(кусок[100:].tolist()) == {0}


def test_частота_приводится_к_микрофонной(опора):
    """Играем на 24 кГц, слушаем на 16 кГц. Разная частота дала бы не эхо,
    а шум."""
    опора.положить(_тон(2400, частота=24000), 24000)

    assert опора.в_очереди == pytest.approx(1600, abs=2)


def test_очередь_не_растёт_бесконечно(опора):
    """Всё, что старше полусекунды, для вычитания бесполезно, а память
    занимает."""
    for _ in range(20):
        опора.положить(_тон(4000), _ЧАСТОТА)

    assert опора.в_очереди <= 8000


def test_сброс_забывает_хвост(опора):
    """Начинается новая реплика: хвост прошлой сдвинул бы выравнивание,
    а выравнивание здесь и есть вычитание."""
    опора.положить(_тон(1600), _ЧАСТОТА)
    опора.сбросить()

    assert опора.в_очереди == 0


def test_пустой_кусок_не_кладётся(опора):
    опора.положить(b"", _ЧАСТОТА)
    assert опора.в_очереди == 0


# ─── Вычитание по-настоящему ─────────────────────────────────────────────────

def _шум(n: int, уровень: float = 0.2, seed: int = 0) -> np.ndarray:
    """Шумоподобный сигнал — модель живого голоса, а не чистый тон.

    Чистый тон для адаптивного фильтра вырожден: одна частота не задаёт
    фильтр однозначно, и сходимости на нём не увидеть ни при какой правке.
    """
    rng = np.random.default_rng(seed)
    return np.clip(rng.normal(0, уровень, n) * 32767, -32768, 32767).astype(np.int16)


def test_собственный_голос_вычитается_из_микрофона():
    """Главная проверка всей затеи: то, что мы отдали в колонки, проходит
    через очередь опорного сигнала и вычитается из микрофона.

    Проверяется именно шов: звук кладётся так же, как его кладёт
    воспроизведение, и берётся так же, как его берёт микрофонный колбэк.
    """
    from core.aec_pipeline import AECPipeline

    aec = AECPipeline(sample_rate=_ЧАСТОТА, filter_length=512)
    опора = ОпорныйСигнал(частота_микрофона=_ЧАСТОТА)

    кадр = 1280
    голос = _шум(_ЧАСТОТА * 4, seed=7)
    задержка, тише = int(_ЧАСТОТА * 0.03), 0.5      # 30 мс тракта, -6 дБ

    чистый = микрофон = None
    for k in range(1, 45):
        с = k * кадр
        кусок = голос[с:с + кадр]
        опора.положить(кусок.tobytes(), _ЧАСТОТА)

        # В микрофон он же возвращается позже и тише.
        микрофон = (голос[с - задержка:с - задержка + кадр] * тише).astype(np.int16)
        чистый, _ = aec.process_frame(микрофон.tobytes(), опора.взять(кадр))

    остаток = np.frombuffer(чистый, dtype=np.int16).astype(np.float64)
    эхо = микрофон.astype(np.float64)
    подавление = 20 * np.log10(
        (np.sqrt(np.mean(эхо ** 2)) + 1e-9) / (np.sqrt(np.mean(остаток ** 2)) + 1e-9))

    assert подавление > 6.0, f"собственный голос почти не вычелся: {подавление:.1f} дБ"


def test_живая_речь_не_съедается():
    """Обратная сторона: пока в колонках тишина, вычитать нечего, и голос
    человека обязан дойти до детектора нетронутым."""
    from core.aec_pipeline import AECPipeline

    aec = AECPipeline(sample_rate=_ЧАСТОТА)
    опора = ОпорныйСигнал(частота_микрофона=_ЧАСТОТА)

    речь = _шум(320, seed=1).tobytes()
    чистый, _ = aec.process_frame(речь, опора.взять(320))

    assert чистый == речь
