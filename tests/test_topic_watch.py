@pytest.fixture
def сторож(tmp_path, monkeypatch):
    """Свежий сторож с диском в tmp_path и поиском-заглушкой."""
    watcher.reset()
    monkeypatch.setattr(watcher, "_файл", lambda: tmp_path / "topics.json")

    class _Мир:
        def __init__(self):
            self.ответ = ""
            self.сказано: list[str] = []
            self.спрошено: list[str] = []

        def искать(self, тема, режим):
            self.спрошено.append(тема)
            return self.ответ

        def говорить(self, текст):
            self.сказано.append(текст)

    мир = _Мир()
    watcher.bind(notify=мир.говорить, search=мир.искать)
    # Фоновый поток в тестах не нужен: обход зовём руками.
    monkeypatch.setattr(watcher, "start", lambda: False)
    yield мир
    watcher.reset()


def _когда(час: int = 14, через_дней: int = 1) -> datetime:
    """Момент обхода: нужный час суток и заведомо больше интервала от «сейчас».

    Фиксированная дата тут не годится — `проверено` пишется настоящим
    `datetime.now()`, и обход «в прошлом» никогда не наступает.
    """
    return (datetime.now() + timedelta(days=через_дней)).replace(
        hour=час, minute=30, second=0, microsecond=0)


