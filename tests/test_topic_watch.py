"""Слежение за темой: заговорить самому — только когда правда есть что сказать.

Всё, что ассистент знал, он узнавал в ответ на вопрос. «Вышла ли прошивка»,
«что там с заказом» — это один и тот же вопрос, заданный двадцать раз за два
дня. Теперь его задают однажды.

Главный риск здесь не в том, что Джарвис промолчит, а в том, что он начнёт
говорить не умолкая: поиск переформулирует один и тот же ответ каждый раз.
Поэтому проверяется в первую очередь МОЛЧАНИЕ — на повторе, на переформулировке
и ночью.
"""

