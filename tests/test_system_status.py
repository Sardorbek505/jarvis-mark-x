"""Состояние машины голосом — и без выдуманных показаний.

Метрики в проекте были, но только там, куда голосом не дотянуться: полоски в
углу HUD и ответ Telegram-бота на `/sys`. Спросить «что с компьютером» вслух
было нельзя.

Проверяется главным образом честность ответа: чего машина не измеряет, о том
не говорят, а числа согласованы с тем, как они произносятся.
"""

import sys
from pathlib import Path

import pytest

_BASE = Path(__file__).resolve().parent.parent
if str(_BASE) not in sys.path:
    sys.path.insert(0, str(_BASE))

from actions import system_monitor as sm

_ПОЛНЫЙ = {
    "cpu": 12.0, "cpu_cores": 8,
    "mem_percent": 41.0, "mem_used_gb": 6.5, "mem_total_gb": 16.0,
    "disk_percent": 55.0, "disk_free_gb": 210.0,
    "uptime_hours": 5.0, "processes": 300,
}


# ─── Согласование числительных: ответ произносят вслух ────────────────────────

@pytest.mark.parametrize("число,ожидание", [
    (1, "процент"), (2, "процента"), (4, "процента"), (5, "процентов"),
    (0, "процентов"), (11, "процентов"), (14, "процентов"),
    (21, "процент"), (22, "процента"), (25, "процентов"),
    (101, "процент"), (112, "процентов"),
])
def test_счётный_падеж(число, ожидание):
    assert sm._склонение(число, sm._ПРОЦЕНТ) == ожидание


def test_дробь_просит_родительный():
    """«0,6 гигабайта», а не «0,6 гигабайт»."""
    assert sm._склонение(0.6, sm._ГИГАБАЙТ, 1) == "гигабайта"
    assert sm._склонение(2.5, sm._ЧАС, 1) == "часа"


def test_согласование_идёт_по_показанному_числу():
    """29,2 произносится как «29» — значит, «29 гигабайт», а не «гигабайта»."""
    assert sm._склонение(29.2, sm._ГИГАБАЙТ, 0) == "гигабайт"
    assert sm._склонение(21.7, sm._ГИГАБАЙТ, 0) == "гигабайта"   # показано «22»


# ─── Честность ответа ─────────────────────────────────────────────────────────

def test_недоступную_температуру_не_выдумываем(monkeypatch):
    """Ноль градусов, произнесённый вслух, звучит как показание."""
    monkeypatch.setattr(sm, "_cpu_temp", lambda: None)
    monkeypatch.setattr(sm, "_gpu", lambda: None)

    фраза = sm._фраза(_ПОЛНЫЙ)

    assert "градус" not in фраза
    assert "видеокарт" not in фраза


def test_доступная_температура_называется():
    фраза = sm._фраза({**_ПОЛНЫЙ, "cpu_temp": 61.0})
    assert "61 градус" in фраза


def test_видеокарта_упоминается_если_есть():
    фраза = sm._фраза({**_ПОЛНЫЙ, "gpu_load": 73.0, "gpu_temp": 64.0})
    assert "видеокарта на 73" in фраза


def test_батарея_различает_сеть_и_автономность():
    от_сети = sm._фраза({**_ПОЛНЫЙ, "battery_percent": 88.0, "battery_plugged": True})
    автономно = sm._фраза({**_ПОЛНЫЙ, "battery_percent": 12.0, "battery_plugged": False})

    assert "от сети" in от_сети
    assert "от батареи" in автономно


def test_настольный_компьютер_про_батарею_молчит():
    assert "батаре" not in sm._фраза(_ПОЛНЫЙ)


def test_в_ответе_нет_знаков_и_единиц_для_глаз():
    """Это читают вслух: «41%» и «6.5 GB» произносятся неудачно."""
    фраза = sm._фраза({**_ПОЛНЫЙ, "battery_percent": 50.0, "battery_plugged": False})

    assert "%" not in фраза
    assert "GB" not in фраза and "МБ" not in фраза


# ─── Время работы ─────────────────────────────────────────────────────────────

def test_свежая_загрузка_не_называется_нулём_часов():
    фраза = sm._фраза({**_ПОЛНЫЙ, "uptime_hours": 0.2})
    assert "0 часов" not in фраза
    assert "меньше часа" in фраза


def test_долгая_работа_считается_сутками():
    фраза = sm._фраза({**_ПОЛНЫЙ, "uptime_hours": 24 * 9})
    assert "9 суток" in фраза


# ─── Пороги ───────────────────────────────────────────────────────────────────

def test_спокойная_машина_поводов_не_даёт():
    assert sm.alerts(_ПОЛНЫЙ) == []


def test_перегрузка_и_нагрев_попадают_в_ответ():
    данные = {**_ПОЛНЫЙ, "cpu": 97.0, "cpu_temp": 91.0}

    поводы = sm.alerts(данные)
    фраза = sm._фраза(данные)

    assert len(поводы) == 2
    assert "внимание" in фраза, "повод обязан прозвучать без отдельного вопроса"


def test_забитый_диск_замечают():
    поводы = sm.alerts({**_ПОЛНЫЙ, "disk_percent": 97.0, "disk_free_gb": 3.4})
    assert поводы and "диске" in поводы[0]


# ─── Сбор и подключение ───────────────────────────────────────────────────────

def test_снимок_содержит_основное():
    данные = sm.collect()

    assert "error" not in данные
    for ключ in ("cpu", "mem_percent", "disk_percent", "uptime_hours"):
        assert ключ in данные


def test_без_psutil_отвечаем_внятно(monkeypatch):
    import builtins
    настоящий = builtins.__import__

    def без_psutil(имя, *a, **kw):
        if имя == "psutil":
            raise ImportError("нет psutil")
        return настоящий(имя, *a, **kw)

    monkeypatch.setattr(builtins, "__import__", без_psutil)

    assert "psutil" in sm.system_status({})


def test_инструмент_подхвачен_реестром():
    """Файл добавили — и всё: ни строчки в main.py."""
    import main

    assert main._ACTIONS.has("system_status")
    assert "system_status" in {t["name"] for t in main.TOOLS}


def test_запрос_попадает_в_лог_интерфейса():
    class _Окно:
        def __init__(self):
            self.лог = []

        def write_log(self, text):
            self.лог.append(text)

    окно = _Окно()
    sm.system_status({}, player=окно)

    assert окно.лог and "ЦПУ" in окно.лог[0]
