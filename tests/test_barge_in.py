class _Часы:
    """Время, которое идёт по команде: у правил здесь секунды, а не события."""

    def __init__(self):
        self.сейчас = 1000.0

    def __call__(self):
        return self.сейчас

    def через(self, секунд):
        self.сейчас += секунд


@pytest.fixture
def часы():
    return _Часы()


@pytest.fixture
def политика(часы):
    return Перебивание(часы=часы)


def _говорит(политика, часы, текст="Погода в Ташкенте ясная, двадцать четыре градуса."):
    политика.заговорил(текст)
    часы.через(barge_in.РАЗГОН_СЕК + 0.1)


# ─── Когда обрывать нельзя ───────────────────────────────────────────────────

def test_пока_он_молчит_обрывать_нечего(политика):
    можно, почему = политика.можно_обрывать()
    assert можно is False
    assert "молчит" in почему


def test_первые_полсекунды_ответа_обрыв_не_принимается(политика, часы):
    """Человек позвал его по имени в самом вопросе, и это имя ещё звучит в
    буфере детектора. Без этого правила он обрывал бы себя на первом слове
    каждого ответа."""
    политика.заговорил("Сейчас посмотрю.")

    часы.через(0.2)
    можно, почему = политика.можно_обрывать()

    assert можно is False
    assert "только начался" in почему


def test_собственное_имя_в_ответе_не_обрывает(политика, часы):
    """Он может произнести слово «Джарвис» сам — в ответе о себе, при чтении
    письма, в пересказе. Замолкать от звука собственного имени он не должен."""
    _говорит(политика, часы, "Меня зовут Джарвис, сэр.")

    можно, почему = политика.можно_обрывать()

    assert можно is False
    assert "сам" in почему


def test_латиница_в_имени_тоже_считается(политика, часы):
    _говорит(политика, часы, "Это проект JARVIS Mark X, сэр.")
    assert политика.можно_обрывать()[0] is False


def test_второй_обрыв_подряд_не_принимается(политика, часы):
    """Слово длиннее одного кадра, и детектор успевает сработать на нём
    дважды. Второе срабатывание — то же самое слово, а не новая просьба."""
    _говорит(политика, часы)
    assert политика.можно_обрывать()[0] is True
    политика.обрыв_принят()

    политика.заговорил("Новый ответ.")
    часы.через(barge_in.РАЗГОН_СЕК + 0.1)
    можно, почему = политика.можно_обрывать()

    assert можно is False
    assert "только что перебивали" in почему


def test_через_кулдаун_обрывать_снова_можно(политика, часы):
    _говорит(политика, часы)
    политика.обрыв_принят()

    часы.через(barge_in.КУЛДАУН_СЕК + 0.1)
    политика.заговорил("Ещё один ответ.")
    часы.через(barge_in.РАЗГОН_СЕК + 0.1)

    assert политика.можно_обрывать()[0] is True


# ─── Когда можно ─────────────────────────────────────────────────────────────

def test_имя_посреди_длинного_ответа_обрывает(политика, часы):
    _говорит(политика, часы)
    assert политика.можно_обрывать() == (True, "")


def test_после_обрыва_он_считается_замолчавшим(политика, часы):
    _говорит(политика, часы)
    политика.обрыв_принят()
