# ─── Пороги ──────────────────────────────────────────────────────────────────

def test_пока_говорит_порог_выше(политика, часы):
    """В микрофоне звучит он сам. Цена ложного срабатывания здесь не «лишнее
    пробуждение», а оборванный на полуслове ответ."""
    молча = политика.пороги
    политика.заговорил("что-нибудь")
    говорит = политика.пороги

    assert говорит[0] > молча[0]
    assert говорит[1] > молча[1]


def test_после_молчания_пороги_возвращаются(политика):
    политика.заговорил("что-нибудь")
    политика.замолчал()
    assert политика.пороги == barge_in.ПОРОГИ_МОЛЧА


# ─── Механика гашения ────────────────────────────────────────────────────────

import main as jarvis_main  # noqa: E402


class _Окно:
    muted = False

    def __init__(self):
        self.логи: list[str] = []
        self.состояния: list[str] = []

    def write_log(self, текст):
        self.логи.append(текст)

    def set_state(self, состояние):
        self.состояния.append(состояние)


def _джарвис(говорит=True):
    j = jarvis_main.Jarvis.__new__(jarvis_main.Jarvis)
    j.ui = _Окно()
    import threading
    j._speaking_lock = threading.Lock()
    j._is_speaking = говорит
    j._wake_detector = None
    j._barge = Перебивание()
    j._speech_gen = 0
    j._loop = None
    j.audio_in_queue = asyncio.Queue()
    j.сказанное = []
    j._say_attention = lambda: j.сказанное.append("отклик")
    if говорит:
        j._barge.заговорил("длинный ответ")
    return j


def test_гашение_вычерпывает_очередь_звука():
    """Без этого он «замолчит» и через секунду договорит хвост, который лежал
    в очереди. Это хуже, чем не перебивать вовсе."""
    j = _джарвис()
    for _ in range(12):
        j.audio_in_queue.put_nowait(b"\x00\x01" * 100)

    j._silence_now("проба")

    assert j.audio_in_queue.empty()


def test_гашение_поднимает_номер_реплики():
    """Синтез, который уже идёт, сверяет номер перед каждым куском — иначе он
    продолжит докладывать готовое в только что вычерпанную очередь."""
    j = _джарвис()
    было = j._speech_gen

    j._silence_now("проба")

    assert j._speech_gen > было


def test_гашение_снимает_признак_речи():
    """Иначе микрофонный шлюз останется закрытым и сказанное следом никуда
    не уедет."""
    j = _джарвис()
    j._silence_now("проба")
    assert j._is_speaking is False


def test_обрыв_именем_откликается_а_клавишей_молчит():
    """Именем — человек позвал и ждёт ответа. Клавишей — он смотрит на экран
    и сам видит, что звук прекратился."""
    голосом = _джарвис()
    голосом._silence_now("услышал своё имя", откликаться=True)

    клавишей = _джарвис()
    клавишей._silence_now("нажали Escape")

    assert голосом.сказанное == ["отклик"]
    assert клавишей.сказанное == []


def test_причина_обрыва_попадает_в_лог():
    """«Он замолчал» должно превращаться в конкретный ответ, а не в догадку."""
    j = _джарвис()
    j._silence_now("услышал своё имя")
    assert any("услышал своё имя" in с for с in j.ui.логи)


# ─── Проводка в микрофонном цикле ────────────────────────────────────────────

class _Детектор:
    def __init__(self, слышит=False):
        self.слышит = слышит
        self.кадры = 0
        self.threshold_stage1 = 0.0
        self.threshold_stage2 = 0.0
        self.сбросов = 0

    def process_pcm(self, pcm):
        self.кадры += 1
        return self.слышит

    def reset(self):
        self.сбросов += 1


class _Кадр:
    @staticmethod
    def tobytes():
        return b"\x00\x01" * 640


def test_кадры_идут_в_детектор_даже_когда_обрыв_запрещён():
    """Детектору нужен непрерывный поток: слово, начатое в «запретную» долю
    секунды, иначе не соберётся."""
    j = _джарвис()
    j._wake_detector = _Детектор(слышит=True)
    j._barge.заговорил("Сейчас посмотрю.")      # разгон ещё не прошёл
    j._note_gate = lambda причина=None: None

    j._listen_for_name(_Кадр())

    assert j._wake_detector.кадры == 1
    assert j.сказанное == []                    # но обрыва не случилось


def test_пороги_детектора_ставятся_под_состояние():
    j = _джарвис()
    j._wake_detector = _Детектор()
    j._note_gate = lambda причина=None: None

    j._feed_name_detector(_Кадр(), слушать=True)

    assert j._wake_detector.threshold_stage1 == barge_in.ПОРОГИ_РЕЧЬ[0]
    assert j._wake_detector.threshold_stage2 == barge_in.ПОРОГИ_РЕЧЬ[1]


def test_сломанный_детектор_не_роняет_поток_звука():
    """Колбэк звуковой карты обязан вернуться раньше следующего кадра.
    Исключение здесь — это заикание звука у всей системы."""
    j = _джарвис()

    class _Битый:
        threshold_stage1 = 0.0
        threshold_stage2 = 0.0

        def process_pcm(self, pcm):
            raise RuntimeError("модель не загрузилась")

    j._wake_detector = _Битый()
    j._note_gate = lambda причина=None: None

    assert j._feed_name_detector(_Кадр(), слушать=True) is False


def test_без_детектора_ничего_не_происходит():
    j = _джарвис()
    j._wake_detector = None
    j._note_gate = lambda причина=None: None

    j._listen_for_name(_Кадр())      # не должно поднять исключение


def test_начало_речи_чистит_буфер_детектора():
    """То самое главное правило: к первому слову ответа имя, сказанное
    человеком в вопросе, ещё лежит в двухсекундном буфере."""
    j = _джарвис(говорит=False)
    j._wake_detector = _Детектор()
    j.ui.muted = False

    j.set_speaking(True)

    assert j._wake_detector.сбросов == 1
    assert j._barge.говорит is True


def test_повторный_признак_речи_не_перезапускает_разгон():
    """`set_speaking(True)` зовётся на КАЖДЫЙ кусок звука. Если бы отсчёт
    начинался заново, разгон не кончался бы никогда и обрыв был бы невозможен."""
    j = _джарвис(говорит=False)
    j._wake_detector = _Детектор()

    j.set_speaking(True)
    j.set_speaking(True)
    j.set_speaking(True)

    assert j._wake_detector.сбросов == 1
