"""Перебить Джарвиса можно, назвав его по имени. И только так.

Полное перебивание «на любую речь», как у Алисы и Сири, для комнаты с
телевизором не годится: в этом же проекте замерено, что музыка даёт RMS
7000-14000 — ровно как живая речь, и по громкости они неразличимы. Каждая
реплика из фильма обрывала бы ответ на полуслове.

Главная ловушка здесь не техническая, а речевая: человек зовёт его ПО ИМЕНИ.
К первому слову ответа слово «Джарвис» ещё лежит в буфере детектора —
сказанное самим человеком полторы секунды назад. Без защиты Джарвис обрывал
бы себя на первом слове КАЖДОГО ответа.
"""

import asyncio
