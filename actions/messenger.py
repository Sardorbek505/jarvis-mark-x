"""
Действие: написать человеку в мессенджер.

ЧТО ЭТО ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ
    Открывает переписку с нужным человеком и вставляет туда готовый текст.
    Отправку нажимает сам человек.

    Соблазн дожать последний шаг велик: в `wa.me` после загрузки достаточно
    послать Enter. Но проверить, что чат открылся, что открылся ТОТ чат и что
    фокус стоит в поле ввода, нечем — из другого процесса это просто
    невидимо. Цена ошибки несимметрична: не отправленное сообщение человек
    отправит сам за секунду, отправленное не тому человеку не отзывается
    никак. Поэтому последнее нажатие остаётся за ним, и в ответе прямо
    сказано, что сообщение НЕ отправлено.

ОТКУДА БЕРЁТСЯ НОМЕР
    Голосом номер не диктуют — говорят «напиши маме». Поэтому здесь есть
    маленькая записная книжка: `save_contact` кладёт имя и номер в
    `~/.jarvis/contacts.json`, дальше достаточно имени.

ПОЧЕМУ НОМЕР НЕ УГАДЫВАЕТСЯ
    Из десяти цифр без кода страны нельзя понять, российский это номер или
    узбекский. Угадать — значит открыть переписку с посторонним человеком и
    вставить туда чужой текст. Такой номер отклоняется с просьбой назвать его
    целиком; про единственное исключение (привычная восьмёрка вместо +7)
    сказано в ответе вслух, чтобы ошибка была видна сразу.
"""

import json
import logging
import re
import urllib.parse
from pathlib import Path

_logger = logging.getLogger(__name__)

_ПРИЛОЖЕНИЯ = {
    "whatsapp": ("WhatsApp", "ватсап", "вотсап", "вацап"),
    "telegram": ("Telegram", "телеграм", "телега"),
}


# ─── Записная книжка ─────────────────────────────────────────────────────────

def _файл() -> Path:
    d = Path.home() / ".jarvis"
    d.mkdir(parents=True, exist_ok=True)
    return d / "contacts.json"


def _контакты() -> dict:
    try:
        данные = json.loads(_файл().read_text(encoding="utf-8"))
        return данные if isinstance(данные, dict) else {}
    except FileNotFoundError:
        return {}
    except Exception as exc:
        _logger.warning("Контакты не прочитаны: %s", exc)
        return {}


def _сохранить(книжка: dict) -> None:
    from core.storage import atomic_write_json
    atomic_write_json(_файл(), книжка)


_ОКОНЧАНИЯ = "аеёиоуыэюяьй"


def _основа(имя: str) -> str:
    """Имя без падежного окончания: «маме» и «мама» — один человек.

    Голосом говорят «напиши МАМЕ», «скинь ДИМЕ», а в книжке записано «мама» и
    «Дима». Нечёткое сравнение здесь не годится: «Дима» и «Дина» похожи на
    75 баллов, то есть ровно настолько же, насколько «Дима» и «Диме», — и
    выбор между ними оказался бы монеткой. Отсечение хвостовых гласных
    различает их точно: «дим» против «дин».
    """
    основа = (имя or "").strip().lower().rstrip(_ОКОНЧАНИЯ)
    # Короткие имена («Зоя», «Ия») окончание съедает целиком — там сравниваем
    # как есть.
    return основа if len(основа) >= 3 else (имя or "").strip().lower()


def _найти_контакт(имя: str) -> tuple[str, str] | None:
    """Имя и номер по тому, как человек назвал контакт вслух."""
    искомое = (имя or "").strip().lower()
    if not искомое:
        return None
    книжка = _контакты()
    for записанное, номер in книжка.items():
        if записанное.lower() == искомое:
            return записанное, номер
    корень = _основа(искомое)
    for записанное, номер in книжка.items():
        if _основа(записанное) == корень:
            return записанное, номер
    for записанное, номер in книжка.items():
        if искомое in записанное.lower() or записанное.lower() in искомое:
            return записанное, номер
    return None


# ─── Номер ───────────────────────────────────────────────────────────────────

_ЦИФРЫ = re.compile(r"\d+")


def _номер(строка: str) -> tuple[str | None, str]:
    """Номер в международном виде и объяснение, если не получилось."""
    сырой = (строка or "").strip()
    цифры = "".join(_ЦИФРЫ.findall(сырой))
    if not цифры:
        return None, "Это не похоже на номер, сэр."

    # Привычная восьмёрка вместо кода страны. Единственная догадка, которую
    # здесь позволено делать: 11 цифр с восьмёрки — это российский номер, и
    # другого прочтения у такой записи нет.
    if len(цифры) == 11 and цифры.startswith("8"):
        цифры = "7" + цифры[1:]

    if len(цифры) < 11:
        return None, ("Назовите номер целиком, с кодом страны, сэр: "
                      "по коротким цифрам страну не угадать, а ошибка здесь "
                      "означает переписку с посторонним человеком.")
    if len(цифры) > 15:
        return None, "Такого длинного номера не бывает, сэр."
    return цифры, ""


def _показать(номер: str) -> str:
    return "+" + номер


# ─── Отправка ────────────────────────────────────────────────────────────────

def _приложение(название: str) -> str:
    низкое = (название or "").strip().lower()
    for ключ, имена in _ПРИЛОЖЕНИЯ.items():
        if низкое == ключ or any(и.lower() in низкое for и in имена):
            return ключ
    return "whatsapp"


def _ссылка(приложение: str, номер: str, текст: str) -> str:
    закодированный = urllib.parse.quote(текст or "")
    if приложение == "telegram":
        # tg://resolve открывает установленный Telegram с готовым текстом.
        # Веб-версия по ссылке текст не подставляет, поэтому именно схема.
        return f"tg://resolve?phone={номер}&text={закодированный}"
    return f"https://wa.me/{номер}?text={закодированный}"


def _открыть(url: str) -> None:
    from actions.browser_control import _open_url
    _open_url(url)


def _написать(кому: str, текст: str, приложение: str, player=None) -> str:
    if not текст.strip():
        return "Что написать, сэр?"
    if not кому.strip():
        return "Кому написать, сэр?"

    контакт = _найти_контакт(кому)
    if контакт:
        имя, сырой_номер = контакт
    else:
        имя, сырой_номер = кому.strip(), кому

    номер, беда = _номер(сырой_номер)
    if номер is None:
        if контакт is None and not any(с.isdigit() for с in кому):
            return (f"Я не знаю номера «{кому}», сэр. Скажите его — и я запомню: "
                    f"«запиши номер {кому}: плюс семь…».")
        return беда

    _открыть(_ссылка(приложение, номер, текст))
    название = _ПРИЛОЖЕНИЯ[приложение][0]
    if player:
        player.write_log(f"MSG: {название} → {имя} ({_показать(номер)})")

    # Никакого «отправил»: отправку нажимает человек, и обещать сделанное
    # за него — худшее, что здесь можно сказать.
    подпись = имя if контакт else _показать(номер)
    return (f"Открыл переписку с {подпись} в {название}, текст готов: «{текст}». "
            f"Нажмите отправку, сэр — сам я этого не делаю.")


# ─── Действия со списком ─────────────────────────────────────────────────────

def _запомнить(имя: str, телефон: str) -> str:
    имя = (имя or "").strip()
    if not имя:
        return "Чей номер запомнить, сэр?"
    номер, беда = _номер(телефон)
    if номер is None:
        return беда

    книжка = _контакты()
    прежний = книжка.get(имя)
    книжка[имя] = номер
    _сохранить(книжка)

    if прежний and прежний != номер:
        return (f"Заменил номер {имя}: было {_показать(прежний)}, "
                f"стало {_показать(номер)}.")
    return f"Запомнил: {имя} — {_показать(номер)}."


def _забыть(имя: str) -> str:
    контакт = _найти_контакт(имя)
    if контакт is None:
        return f"«{имя}» в книжке нет, сэр."
    книжка = _контакты()
    книжка.pop(контакт[0], None)
    _сохранить(книжка)
    return f"Убрал {контакт[0]} из книжки, сэр."


def _перечислить() -> str:
    книжка = _контакты()
    if not книжка:
        return "Книжка пуста, сэр. Скажите «запиши номер мамы», и я начну её."
    части = [f"{имя} — {_показать(номер)}" for имя, номер in sorted(книжка.items())]
    return f"В книжке {len(книжка)}: " + ", ".join(части) + "."


def messenger(parameters: dict, player=None) -> str:
    параметры = parameters or {}
    действие = str(параметры.get("action", "send")).strip().lower()
    кому = str(параметры.get("to", "")).strip()
    текст = str(параметры.get("text", "")).strip()
    телефон = str(параметры.get("phone", "")).strip()

    if действие in ("save_contact", "save", "запомни"):
        return _запомнить(кому, телефон)
    if действие in ("forget_contact", "forget", "забудь"):
        return _забыть(кому)
    if действие in ("contacts", "list", "список"):
        return _перечислить()
    return _написать(кому, текст, _приложение(параметры.get("app", "")), player)


