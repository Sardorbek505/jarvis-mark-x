"""
Действие: запустить скрипт и рассказать, что он вывел.

ПОЧЕМУ ЭТО ЗА КНОПКОЙ
    Микрофон отдаёт модели всё, что слышит в комнате, включая звук из фильма.
    «Запусти скрипт» — единственное действие во всём наборе, которое
    выполняет ПРОИЗВОЛЬНЫЙ код: отменить его нельзя, и что именно он сделает,
    заранее не знает никто. Поэтому запуск проходит тот же гейт, что
    выключение компьютера: баннер в окне с полным путём и нажатие человеком.

ЧЕГО ЗДЕСЬ НЕТ
    Написания кода. Модель и так умеет писать текст, а положить его в файл
    умеет `files` с action=create_file — отдельный инструмент для этого был бы
    вторым способом делать то же самое. В описании модель отправляется туда.

    Ни установки пакетов, ни сборки проекта. Скрипт запускается ровно тем
    интерпретатором, который уже стоит в системе, в своей собственной папке.

ПРО ПРОВЕРКУ
    `check` разбирает файл Python, НЕ выполняя его: `compile()` находит
    синтаксическую ошибку с номером строки и ничего при этом не запускает.
    Это самый частый вопрос («почему не работает?») и единственный, на
    который можно ответить безопасно.
"""

import logging
import platform
import shutil
import subprocess
import sys
from pathlib import Path

_logger = logging.getLogger(__name__)

_OS = platform.system()

# Чем запускать. Пусто — значит в этой системе нечем, и об этом надо сказать,
# а не пробовать наугад.
_ЧЕМ = {
    ".py":  lambda: [sys.executable],
    ".js":  lambda: [shutil.which("node")] if shutil.which("node") else [],
    ".sh":  lambda: [shutil.which("bash")] if _OS != "Windows" and shutil.which("bash") else [],
    ".ps1": lambda: [shutil.which("powershell") or "powershell"] if _OS == "Windows" else [],
}

_ТАЙМАУТ_ПО_УМОЛЧАНИЮ = 30
_ТАЙМАУТ_ПРЕДЕЛ = 300

# Сколько вывода писать в лог окна и сколько произносить вслух. Скрипт может
# напечатать мегабайт; зачитывать его вслух — не помощь.
_В_ЛОГ = 2000
_ВСЛУХ = 400


def _обрезать(текст: str, предел: int) -> str:
    текст = (текст or "").strip()
    if len(текст) <= предел:
        return текст
    return текст[:предел].rstrip() + "…"


def _последняя_беда(вывод: str) -> str:
    """Последняя содержательная строка ошибки — там, где у Python лежит тип
    исключения. Зачитывать весь traceback вслух бессмысленно."""
    строки = [с.strip() for с in (вывод or "").splitlines() if с.strip()]
    return строки[-1] if строки else ""


def _файл(параметры: dict, player=None) -> tuple[Path | None, str]:
    путь_строкой = str(параметры.get("file_path", "") or "").strip()
    if not путь_строкой and player is not None:
        путь_строкой = str(getattr(player, "current_file", "") or "")
    if not путь_строкой:
        return None, ("Какой скрипт, сэр? Назовите путь или перетащите файл "
                      "в окно.")

    путь = Path(путь_строкой).expanduser()
    if not путь.is_file():
        return None, f"Файла нет по пути {путь}, сэр."
    return путь, ""


def _проверить(путь: Path, player=None) -> str:
    if путь.suffix.lower() != ".py":
        return (f"Разобрать без запуска я умею только Python, сэр, "
                f"а это {путь.suffix or 'файл без расширения'}.")
    try:
        исходник = путь.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return f"Файл не прочитался, сэр: {exc}"

    try:
        # Именно compile: разбирает и НЕ выполняет. Ни одна строка скрипта
        # при этом не работает.
        compile(исходник, str(путь), "exec")
    except SyntaxError as беда:
        if player:
            player.write_log(f"CODE: ошибка в {путь.name}:{беда.lineno}")
        return (f"Синтаксическая ошибка в {путь.name}, строка {беда.lineno}: "
                f"{беда.msg}.")
    except ValueError as беда:               # нулевые байты и прочая экзотика
        return f"{путь.name} разобрать не вышло, сэр: {беда}"

    if player:
        player.write_log(f"CODE: {путь.name} — синтаксис в порядке")
    return f"Синтаксис {путь.name} в порядке, сэр. Ошибок разбора нет."


def _запустить(путь: Path, аргументы: str, таймаут: int, player=None) -> str:
    собрать = _ЧЕМ.get(путь.suffix.lower())
    if собрать is None:
        return (f"Не знаю, чем запускать {путь.suffix or 'файл без расширения'}, сэр. "
                f"Умею Python, Node, bash и PowerShell.")
    команда = собрать()
    if not команда:
        return (f"{путь.suffix} в этой системе запустить нечем, сэр — "
                f"нужного интерпретатора нет.")

    команда = list(команда) + [str(путь)]
    if аргументы:
        команда += аргументы.split()

    if player:
        player.write_log(f"CODE: запускаю {путь.name}")

    try:
        итог = subprocess.run(
            команда,
            capture_output=True, text=True, timeout=таймаут,
            # В своей папке: скрипт почти всегда рассчитывает на соседние
            # файлы, а не на то, откуда его позвали.
            cwd=str(путь.parent),
        )
    except subprocess.TimeoutExpired:
        return (f"{путь.name} не уложился в {таймаут} секунд, сэр — "
                f"я его остановил.")
    except Exception as exc:
        return f"Запустить {путь.name} не вышло, сэр: {exc}"

    вывод = (итог.stdout or "").strip()
    ошибки = (итог.stderr or "").strip()

    if player:
        if вывод:
            player.write_log(f"CODE: вывод — {_обрезать(вывод, _В_ЛОГ)}")
        if ошибки:
            player.write_log(f"CODE: stderr — {_обрезать(ошибки, _В_ЛОГ)}")

    if итог.returncode != 0:
        беда = _последняя_беда(ошибки) or _последняя_беда(вывод)
        хвост = f" {беда}" if беда else ""
        return (f"{путь.name} завершился с ошибкой (код {итог.returncode}).{хвост} "
                f"Подробности в логе.")

    if not вывод:
        return f"{путь.name} отработал без ошибок, сэр. Ничего не вывел."
    return f"{путь.name} отработал. Вывод: {_обрезать(вывод, _ВСЛУХ)}"


def code_runner(parameters: dict, player=None) -> str:
    параметры = parameters or {}
    действие = str(параметры.get("action", "run")).strip().lower()

    путь, беда = _файл(параметры, player)
    if путь is None:
        return беда

    if действие in ("check", "проверь", "syntax"):
        return _проверить(путь, player)

    try:
        таймаут = int(параметры.get("timeout") or _ТАЙМАУТ_ПО_УМОЛЧАНИЮ)
    except (TypeError, ValueError):
        таймаут = _ТАЙМАУТ_ПО_УМОЛЧАНИЮ
    таймаут = max(1, min(таймаут, _ТАЙМАУТ_ПРЕДЕЛ))

    аргументы = str(параметры.get("args", "") or "").strip()
    return _запустить(путь, аргументы, таймаут, player)


