"""
Действие: найти на экране то, что названо словами, и нажать туда.

ЗАЧЕМ
    «Нажми Сохранить» — просьба, которую человек произносит естественно и
    которую нельзя было выполнить: мышью Джарвис не владел вовсе, а
    координаты голосом не диктуют.

КАК ЭТО РАБОТАЕТ
    Снимок экрана уходит в ту же модель зрения, что отвечает на «что у меня
    на экране», но с другой задачей: вернуть рамку названного элемента в
    нормированных координатах и ТЕКСТ, который на нём написан. По рамке
    считается середина, туда едет курсор.

ГЛАВНОЕ ПРАВИЛО: СОМНЕВАЕШЬСЯ — НЕ НАЖИМАЙ
    Промах мышью — это не «не сработало», это нажатая соседняя кнопка. Между
    «Сохранить» и «Удалить» на панели пара сантиметров, и цена ошибки
    несимметрична настолько, что осторожность здесь дешевле пользы.

    Поэтому клика не будет, если модель не нашла элемент, если она сама
    оценила уверенность как низкую или если прочитанная ею надпись не похожа
    на то, что просил человек. Во всех трёх случаях Джарвис говорит, что
    видит, и предлагает уточнить — курсор при этом не двигается.
"""

import json
import logging
import re

_logger = logging.getLogger(__name__)

# Насколько прочитанная надпись должна быть похожа на просьбу. Ниже — значит
# модель нашла «что-то похожее по смыслу», а нажимать по смыслу нельзя.
#
# Сравнение по СЛОВАМ, а не по буквам, и порог выбран замером. «Удалить» и
# «Сохранить» отличаются на четыре буквы из девяти и по побуквенному сравнению
# похожи на 67 баллов — то есть побуквенно «нажми Сохранить» имело право
# нажать «Удалить». По словам они расходятся до пятидесяти, а настоящие пары
# («Сохранить» и «кнопка Сохранить») дают сто.
_ПОХОЖЕСТЬ = 75

_МОДЕЛЬ = "gemini-2.5-flash"

_ЗАДАЧА = (
    "На снимке экрана компьютера найди элемент, который пользователь описал "
    "словами: «{запрос}».\n\n"
    "Ответь ТОЛЬКО одним объектом JSON, без пояснений и без markdown:\n"
    '{{"found": true|false, "box": [y0, x0, y1, x1], "label": "надпись на '
    'элементе", "confidence": "высокая"|"средняя"|"низкая"}}\n\n'
    "box — рамка элемента в координатах от 0 до 1000, порядок именно такой: "
    "верх, лево, низ, право.\n"
    "label — текст, который РЕАЛЬНО написан на элементе, а не то, что просили.\n"
    "confidence — низкая, если подходящих элементов несколько или ты не уверен.\n"
    "Если такого элемента на экране нет — found: false."
)

_JSON_RE = re.compile(r"\{.*\}", re.DOTALL)


# ─── Снимок и вопрос модели ──────────────────────────────────────────────────

def _снимок():
    """Кадр экрана и его настоящий размер в пикселях."""
    from vision.screen_capture import capture_full_screen, compress_image

    кадр = capture_full_screen()
    if кадр is None:
        return None, 0, 0
    return compress_image(кадр), кадр.width, кадр.height


def _спросить_зрение(запрос: str) -> dict | None:
    """Рамка названного элемента или None, если спросить не вышло."""
    from core.onboarding import ensure_gemini_key

    ключ = (ensure_gemini_key(interactive=False) or "").strip()
    if not ключ:
        return None

    снимок, ширина, высота = _снимок()
    if not снимок:
        return None

    try:
        from google import genai
        from google.genai import types

        клиент = genai.Client(api_key=ключ)
        ответ = клиент.models.generate_content(
            model=_МОДЕЛЬ,
            contents=[
                types.Part.from_bytes(data=снимок, mime_type="image/jpeg"),
                _ЗАДАЧА.format(запрос=запрос),
            ],
            # Ноль температуры: координаты — не то место, где нужна фантазия.
            config=types.GenerateContentConfig(temperature=0.0, max_output_tokens=200),
        )
        текст = (ответ.text or "").strip()
    except Exception as exc:
        _logger.warning("Зрение не ответило: %s", exc)
        return None

    кусок = _JSON_RE.search(текст)
    if not кусок:
        _logger.warning("Зрение ответило не JSON: %s", текст[:120])
        return None
    try:
        разобрано = json.loads(кусок.group(0))
    except json.JSONDecodeError as exc:
        _logger.warning("JSON зрения не разобран: %s", exc)
        return None

    разобрано["_ширина"] = ширина
    разобрано["_высота"] = высота
    return разобрано


def _середина(рамка, ширина: int, высота: int) -> tuple[int, int] | None:
    try:
        y0, x0, y1, x1 = (float(з) for з in рамка)
    except (TypeError, ValueError):
        return None
    x = int((x0 + x1) / 2 / 1000 * ширина)
    y = int((y0 + y1) / 2 / 1000 * высота)
    if not (0 <= x < ширина and 0 <= y < высота):
        return None
    return x, y


def _похоже(надпись: str, запрос: str) -> bool:
    """Совпадает ли прочитанное с тем, что просили."""
    надпись, запрос = (надпись or "").strip().lower(), (запрос or "").strip().lower()
    if not надпись:
        return False
    if надпись in запрос or запрос in надпись:
        return True
    try:
        from rapidfuzz import fuzz
    except ImportError:
        # Без нечёткого сравнения остаётся точное. Строже, чем нужно, — но
        # в эту сторону ошибаться безопасно: лишний отказ, а не лишний клик.
        return False
    return fuzz.token_set_ratio(надпись, запрос) >= _ПОХОЖЕСТЬ


# ─── Мышь ────────────────────────────────────────────────────────────────────

def _мышь():
    try:
        import pyautogui

        return pyautogui
    except Exception as exc:
        _logger.warning("Мышь недоступна: %s", exc)
        return None


def _навести(x: int, y: int, нажать: str = "") -> str:
    """Ведёт курсор и, если просили, нажимает. Пустая строка — получилось."""
    pyautogui = _мышь()
    if pyautogui is None:
        return "Мышью на этой машине управлять нечем, сэр: нет pyautogui."
    try:
        # Полсекунды на переезд: мгновенный скачок курсора часть приложений
        # не замечает, а человек не успевает увидеть, куда именно он уехал.
        pyautogui.moveTo(x, y, duration=0.5)
        if нажать == "double":
            pyautogui.doubleClick()
        elif нажать == "right":
            pyautogui.click(button="right")
        elif нажать == "left":
            pyautogui.click()
    except Exception as exc:
        _logger.warning("Мышь не послушалась: %s", exc)
        return f"Мышь не послушалась, сэр: {exc}"
    return ""


# ─── Действия ────────────────────────────────────────────────────────────────

_НАЖАТИЯ = {"click": "left", "double_click": "double", "right_click": "right",
            "find": "", "move": ""}


def _искать_и_нажать(запрос: str, нажатие: str, player=None) -> str:
    if not запрос:
        return "Что найти на экране, сэр?"

    найденное = _спросить_зрение(запрос)
    if найденное is None:
        return "Посмотреть на экран не вышло, сэр — зрение недоступно."

    if not найденное.get("found"):
        return f"«{запрос}» на экране не вижу, сэр."

    надпись = str(найденное.get("label", "")).strip()
    уверенность = str(найденное.get("confidence", "")).strip().lower()
    точка = _середина(найденное.get("box"), найденное["_ширина"], найденное["_высота"])

    if точка is None:
        return f"Нашёл «{надпись or запрос}», но не понял где, сэр."

    # Три причины не нажимать. Промах мышью — это не «не сработало», это
    # нажатая соседняя кнопка, и цена ошибки несимметрична.
    сомнение = ""
    if уверенность.startswith("низ"):
        сомнение = "я не уверен, что это то самое"
    elif нажатие and not _похоже(надпись, запрос):
        сомнение = f"там написано «{надпись}», а не то, что вы просили"

    if сомнение and нажатие:
        return (f"Нашёл похожее в точке {точка[0]}, {точка[1]}, но {сомнение}, сэр. "
                f"Нажимать не стал — скажите точнее, что искать.")

    беда = _навести(*точка, нажать=нажатие)
    if беда:
        return беда

    if player:
        player.write_log(f"MOUSE: {надпись or запрос} → {точка[0]}, {точка[1]}")

    подпись = надпись or запрос
    if not нажатие:
        return f"Навёл курсор на «{подпись}», сэр."
    глагол = {"left": "Нажал", "double": "Нажал дважды", "right": "Правый клик по"}
    return f"{глагол[нажатие]} «{подпись}», сэр."


def _прокрутить(параметры: dict) -> str:
    pyautogui = _мышь()
    if pyautogui is None:
        return "Мышью на этой машине управлять нечем, сэр: нет pyautogui."
    try:
        шагов = int(параметры.get("amount") or 3)
    except (TypeError, ValueError):
        шагов = 3
    вниз = str(параметры.get("direction", "down")).strip().lower() in ("down", "вниз")
    try:
        pyautogui.scroll(-шагов * 120 if вниз else шагов * 120)
    except Exception as exc:
        return f"Прокрутить не вышло, сэр: {exc}"
    return "Прокрутил, сэр."


def screen_pointer(parameters: dict, player=None) -> str:
    параметры = parameters or {}
    действие = str(параметры.get("action", "find")).strip().lower()
    запрос = str(параметры.get("target", "")).strip()

    if действие in ("scroll", "прокрути"):
        return _прокрутить(параметры)

    нажатие = _НАЖАТИЯ.get(действие)
    if нажатие is None:
        return (f"Не знаю действия «{действие}», сэр. "
                f"Умею: find, move, click, double_click, right_click, scroll.")
    return _искать_и_нажать(запрос, нажатие, player)


