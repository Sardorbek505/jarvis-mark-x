"""
Действие: буфер обмена — прочитать скопированное и положить туда текст.

Механика в `core/clipboard.py`; там же объяснено, почему за буфером здесь
НЕ следят постоянно.

Смысл этого инструмента — в связке с тем, что модель и так умеет. Она не
переводит и не пересказывает «через инструмент»: она получает текст из
буфера и делает это сама. Поэтому здесь ровно два действия, а не пять
кнопок «перевести / пересказать / объяснить».
"""

import logging

from core import clipboard

_logger = logging.getLogger(__name__)

# Сколько показываем в логе окна: буфер бывает на страницу.
_В_ЛОГ = 120


def _укоротить(текст: str, предел: int) -> str:
    текст = " ".join((текст or "").split())
    return текст if len(текст) <= предел else текст[:предел].rstrip() + "…"


def _прочитать(player=None) -> str:
    try:
        текст = clipboard.read()
    except clipboard.БуферНедоступен as беда:
        return f"До буфера обмена не дотянуться, сэр: {беда}."
    except Exception as exc:
        _logger.warning("Буфер не прочитан: %s", exc)
        return "Прочитать буфер обмена не вышло, сэр."

    if not текст.strip():
        return "В буфере обмена пусто, сэр."

    if player:
        player.write_log(f"BUF: прочитал — {_укоротить(текст, _В_ЛОГ)}")
    # Возвращаем текст как есть: переводить, пересказывать и объяснять
    # модель умеет сама, ей нужно только содержимое.
    return f"В буфере обмена: {текст}"


def _положить(текст: str, player=None) -> str:
    if not (текст or "").strip():
        return "Что положить в буфер, сэр?"
    try:
        clipboard.write(текст)
    except clipboard.БуферНедоступен as беда:
        return f"Положить в буфер не вышло, сэр: {беда}."
    except Exception as exc:
        _logger.warning("Буфер не записан: %s", exc)
        return "Положить в буфер не вышло, сэр."

    if player:
        player.write_log(f"BUF: положил — {_укоротить(текст, _В_ЛОГ)}")
    return "Скопировал, сэр — вставляйте."


def clipboard_tool(parameters: dict, player=None) -> str:
    параметры = parameters or {}
    действие = str(параметры.get("action", "read")).strip().lower()
    текст = str(параметры.get("text", "") or "")

    if действие in ("write", "copy", "положи", "скопируй"):
        return _положить(текст, player)
    return _прочитать(player)


# ─── Объявление для реестра действий ──────────────────────────────────────────
TOOL = {
    "name": "clipboard",
    "description": (
        "Буфер обмена. action=read — прочитать то, что пользователь скопировал; "
        "action=write (нужен text) — положить текст в буфер, чтобы он мог вставить. "
        "Вызывай read, когда просят сделать что-то «со скопированным», «с тем, "
        "что в буфере»: переведи, перескажи, объясни, исправь. Полученный текст "
        "обрабатывай САМ — отдельного инструмента для перевода буфера нет. "
        "Вызывай write, когда просят «скопируй это», «положи в буфер», а также "
        "когда написал длинный текст, который человеку удобнее вставить, чем "
        "переписывать со слуха. "
        "Буфер читается только по просьбе: постоянно за ним никто не следит."
    ),
    "parameters": {
        "type": "OBJECT",
        "properties": {
            "action": {"type": "STRING", "description": "read (по умолчанию) | write"},
            "text":   {"type": "STRING", "description": "Что положить в буфер (для write)"},
        },
        "required": [],
    },
    "handler": clipboard_tool,
}
