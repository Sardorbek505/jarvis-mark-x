def set_cell_background(cell, fill_hex):
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{fill_hex}"/>')
    cell._tc.get_or_add_tcPr().append(shd)

def set_cell_margins(cell, top=140, bottom=140, left=200, right=200):
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = parse_xml(f'<w:tcMar {nsdecls("w")}><w:top w:w="{top}" w:type="dxa"/><w:bottom w:w="{bottom}" w:type="dxa"/><w:left w:w="{left}" w:type="dxa"/><w:right w:w="{right}" w:type="dxa"/></w:tcMar>')
    tcPr.append(tcMar)

def add_header_block(doc, title_text):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.autofit = False
    tbl.columns[0].width = Cm(16.5)
    cell = tbl.cell(0, 0)
    set_cell_background(cell, "262626")
    set_cell_margins(cell, top=160, bottom=160, left=240, right=240)
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run(title_text)
    run.font.name = "Arial"
    run.font.size = Pt(13)
    run.font.bold = True
    run.font.color.rgb = RGBColor(255, 255, 255)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)

def add_callout(doc, bg_hex, title, content_lines):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.autofit = False
    tbl.columns[0].width = Cm(16.5)
    cell = tbl.cell(0, 0)
    set_cell_background(cell, bg_hex)
    set_cell_margins(cell, top=140, bottom=140, left=220, right=220)
    
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(4)
    run_t = p.add_run(title)
    run_t.font.name = "Arial"
    run_t.font.size = Pt(11)
    run_t.font.bold = True
    if bg_hex == "E2F0D9":
        run_t.font.color.rgb = RGBColor(39, 110, 43)
    elif bg_hex == "DDEBF7":
        run_t.font.color.rgb = RGBColor(31, 78, 121)
    else:
        run_t.font.color.rgb = RGBColor(40, 40, 40)
        
    for line in content_lines:
        p2 = cell.add_paragraph()
        p2.paragraph_format.space_before = Pt(2)
        p2.paragraph_format.space_after = Pt(2)
        p2.paragraph_format.line_spacing = 1.15
        
        if ":" in line and not line.startswith("http"):
            parts = line.split(":", 1)
            r1 = p2.add_run(parts[0] + ":")
            r1.font.bold = True
            r1.font.name = "Calibri"
            r1.font.size = Pt(10.5)
            r2 = p2.add_run(parts[1])
            r2.font.name = "Calibri"
            r2.font.size = Pt(10.5)
        else:
            r = p2.add_run(line)
            r.font.name = "Calibri"
            r.font.size = Pt(10.5)
            
    doc.add_paragraph().paragraph_format.space_after = Pt(4)

