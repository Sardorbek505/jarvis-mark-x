"""
Слежение за темой: проверять самому и сказать, когда появится новое.

ЗАЧЕМ
    Всё, что ассистент знает, он узнаёт в ответ на вопрос. «Что там с
    заказом», «вышла ли прошивка», «что пишут про запуск» — это не один
    вопрос, а один и тот же вопрос, заданный двадцать раз за два дня. Между
    заданиями человек либо забывает, либо проверяет сам.

    Здесь он говорит это один раз. Дальше проверяет Джарвис и молчит, пока
    нечего сказать.

ЧТО СЧИТАЕТСЯ НОВЫМ
    Не «ответ поиска изменился»: поиск переформулирует одно и то же каждый
    раз, и такой ассистент заговорил бы через полчаса и не замолкал. Каждое
    предложение ответа сравнивается с тем, что уже произносилось, нестрого
    (rapidfuzz): переписанный другими словами заголовок — не новость.

    Отсюда и граница применимости, о которой сказано прямо в описании
    инструмента: это слежение за СОБЫТИЯМИ — вышло, объявили, отменили. Не
    за третьим знаком после запятой в курсе валют: «92,31» и «92,35» — одно
    и то же предложение, и оно не прозвучит. Обещать точность, которой нет,
    хуже, чем не обещать ничего.

ПОЧЕМУ ТАК МАЛО ТЕМ И ТАК РЕДКО
    Ассистент, заговаривающий сам, — гость, а не сторож. Пять тем, не чаще
    раза в четверть часа и ни слова ночью: превышение этих чисел превращает
    полезное в невыносимое быстрее, чем человек успевает найти, где это
    выключается.

ПЕРВАЯ ПРОВЕРКА МОЛЧИТ
    Она делается сразу, при постановке на слежение, и её результат уходит в
    ответ — человек и так спросил. Заодно она становится точкой отсчёта:
    иначе через минуту Джарвис объявил бы новостью то, что только что сам и
    рассказал.
"""

import json
import logging
import re
import subprocess
import threading
from datetime import datetime
from pathlib import Path

_logger = logging.getLogger(__name__)

# ─── Границы, за которыми полезное становится невыносимым ────────────────────
МАКС_ТЕМ = 5
МИН_ИНТЕРВАЛ_МИН = 15
ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МИН = 30
ПАМЯТЬ_ОТПЕЧАТКОВ = 40          # сколько произнесённого помним на тему
# Порог «это уже говорилось». Выбран по замеру, а не на глаз: пересказ одной
# и той же новости другими словами даёт 78–96 баллов сходства, а разные
# новости по одной теме — около пятидесяти. Восемьдесят стоит посреди этого
# разрыва, ближе к разговорчивому краю: пропустить оттенок не так дорого, как
# получить ассистента, который повторяет одно и то же весь день.
СХОЖЕСТЬ = 80
ТИХО_С, ТИХО_ДО = 23, 8         # часы, в которые Джарвис молчит
ТАКТ_СЕК = 60                   # как часто просыпается фоновый поток
МАКС_НОВОСТЕЙ_ЗА_РАЗ = 2        # больше за один раз человек не слушает

_замок = threading.RLock()
_темы: list[dict] = []
_загружено = False

_notify = None                  # куда сказать новое (в Live-сессию)
_log = None                     # куда написать для человека в окно
_search = None                  # чем проверять; по умолчанию — web_search

_поток: threading.Thread | None = None
_стоп = threading.Event()


# ─── Хранение ────────────────────────────────────────────────────────────────

def _файл() -> Path:
    """Рядом с настройками пользователя, а не в папке программы: программу
    могут переустановить, а слежение должно пережить это."""
    d = Path.home() / ".jarvis" / "watch"
    d.mkdir(parents=True, exist_ok=True)
    return d / "topics.json"


def _прочитать() -> list[dict]:
    try:
        данные = json.loads(_файл().read_text(encoding="utf-8"))
        return данные if isinstance(данные, list) else []
    except FileNotFoundError:
        return []
    except Exception as exc:
        _logger.warning("Список слежения не прочитан: %s", exc)
        return []


def _записать() -> None:
    try:
        from core.storage import atomic_write_json
        atomic_write_json(_файл(), _темы)
    except Exception as exc:
        _logger.warning("Список слежения не сохранён: %s", exc)


def _загрузить() -> None:
    global _загружено
    with _замок:
        if _загружено:
            return
        _темы[:] = _прочитать()
        _загружено = True


# ─── Что считается новым ─────────────────────────────────────────────────────

_ПРОБЕЛЫ = re.compile(r"\s+")
_ЛИШНЕЕ = re.compile(r"[^\w\s]", re.UNICODE)


def _нормализовать(строка: str) -> str:
    return _ПРОБЕЛЫ.sub(" ", _ЛИШНЕЕ.sub(" ", строка.lower())).strip()


def _на_куски(текст: str) -> list[str]:
    """Ответ поиска — на отдельные утверждения.

    Границей считается конец предложения или перевод строки. Огрызки короче
    двадцати пяти символов отбрасываются: «Да.», «Источник: РБК» — это не то,
    ради чего стоит заговаривать с человеком."""
    куски = re.split(r"(?<=[.!?…])\s+|\n+", текст or "")
    return [к.strip() for к in куски if len(к.strip()) >= 25]


def _похоже(кусок: str, известное: list[str]) -> bool:
    эталон = _нормализовать(кусок)
    if not эталон:
        return True
    if эталон in известное:
        return True
    try:
        from rapidfuzz import fuzz
    except ImportError:
        # Без нечёткого сравнения остаётся точное. Это строже, чем нужно:
        # переформулировка пройдёт как новость. Лучше лишняя фраза раз в
        # полчаса, чем молчание там, где новость настоящая.
        return False
    return any(fuzz.ratio(эталон, з) >= СХОЖЕСТЬ for з in известное)


def _новое(текст: str, известное: list[str]) -> list[str]:
    свежее = []
    накопленное = list(известное)
    for кусок in _на_куски(текст):
        if _похоже(кусок, накопленное):
            continue
        свежее.append(кусок)
        накопленное.append(_нормализовать(кусок))
    return свежее


# ─── Подключение к живому ассистенту ─────────────────────────────────────────

def bind(notify=None, log=None, search=None) -> None:
    """Куда говорить, куда писать и чем проверять. Без `notify` слежение
    работает вхолостую: проверить может, сказать — некому."""
    global _notify, _log, _search
    _notify = notify
    _log = log
    _search = search


def _проверить(тема: dict) -> str:
    """Спрашивает мир о теме. Отдельная функция — чтобы тест не ходил в сеть."""
    if _search is not None:
        return _search(тема["тема"], тема.get("режим", "news"))
    from actions.web_search import web_search
    return web_search({"query": тема["тема"], "mode": тема.get("режим", "news")})


# ─── Работа со списком ───────────────────────────────────────────────────────

def _найти(тема: str) -> dict | None:
    искомое = _нормализовать(тема)
    for з in _темы:
        if _нормализовать(з["тема"]) == искомое:
            return з
    # Человек называет тему не теми же словами, что вчера: «доллар» вместо
    # «курс доллара». Вхождение подстроки здесь надёжнее точного совпадения.
    for з in _темы:
        if искомое and искомое in _нормализовать(з["тема"]):
            return з
    return None


def add(тема: str, режим: str = "news", интервал_мин: int | None = None,
        уведомлять: bool = False) -> str:
    """Ставит тему на слежение и СРАЗУ отвечает, что по ней сейчас."""
    _загрузить()
    тема = (тема or "").strip()
    if not тема:
        return "За чем следить, сэр?"

    with _замок:
        if _найти(тема):
            return f"За «{тема}» я уже слежу, сэр."
        if len(_темы) >= МАКС_ТЕМ:
            имена = ", ".join(f"«{з['тема']}»" for з in _темы)
            return (f"Больше {МАКС_ТЕМ} тем сразу я не веду, сэр — иначе начну "
                    f"перебивать вас. Сейчас слежу за: {имена}. "
                    f"Скажите, от какой отказаться.")

        интервал = max(МИН_ИНТЕРВАЛ_МИН, int(интервал_мин or ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МИН))
        запись = {
            "тема": тема,
            "режим": (режим or "news").strip().lower() or "news",
            "интервал": интервал,
            "создано": datetime.now().isoformat(timespec="seconds"),
            "проверено": None,
            "известное": [],
            "уведомлять": bool(уведомлять),
        }

    # Первая проверка — вне замка: она ходит в сеть и занимает секунды.
    try:
        ответ = _проверить(запись)
    except Exception as exc:
        _logger.warning("Первая проверка «%s» сорвалась: %s", тема, exc)
        ответ = ""

    запись["известное"] = [_нормализовать(к) for к in _на_куски(ответ)][-ПАМЯТЬ_ОТПЕЧАТКОВ:]
    запись["проверено"] = datetime.now().isoformat(timespec="seconds")

    with _замок:
        _темы.append(запись)
        _записать()
    start()

    if _log:
        _log(f"SYS: слежу за «{тема}», проверка раз в {интервал} мин")

    каждые = f"Буду проверять раз в {интервал} минут и скажу, когда появится новое."
    if not ответ:
        return f"Взял «{тема}» под наблюдение, сэр. {каждые}"
    return f"{ответ} Взял «{тема}» под наблюдение. {каждые}"


def remove(тема: str = "") -> str:
    _загрузить()
    # Останов потока — ПОСЛЕ замка, а не под ним: поток в это время может
    # ждать того же замка внутри обхода, и join() под замком встал бы ровно
    # на свой таймаут.
    гасить = False
    with _замок:
        if not _темы:
            ответ = "Я ни за чем не слежу, сэр."
        elif not тема:
            сколько = len(_темы)
            _темы.clear()
            _записать()
            гасить = True
            ответ = f"Снял наблюдение со всех тем, сэр. Было {сколько}."
        else:
            запись = _найти(тема)
            if запись is None:
                ответ = f"За «{тема}» я не слежу, сэр."
            else:
                _темы.remove(запись)
                _записать()
                гасить = not _темы
                ответ = f"Больше за «{запись['тема']}» не слежу, сэр."

    if гасить:
        stop()
    return ответ


def topics() -> list[dict]:
    _загрузить()
    with _замок:
        return [dict(з) for з in _темы]


def describe() -> str:
    записи = topics()
    if not записи:
        return "Сейчас я ни за чем не слежу, сэр."
    части = [f"«{з['тема']}» (раз в {з['интервал']} мин)" for з in записи]
    return f"Слежу за {len(записи)}: " + ", ".join(части) + "."


# ─── Проверка и голос ────────────────────────────────────────────────────────

def _пора(запись: dict, сейчас: datetime) -> bool:
    когда = запись.get("проверено")
    if not когда:
        return True
    try:
        прошло = (сейчас - datetime.fromisoformat(когда)).total_seconds()
    except (TypeError, ValueError):
        return True
    return прошло >= запись.get("интервал", ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МИН) * 60


def тихо(сейчас: datetime | None = None) -> bool:
    час = (сейчас or datetime.now()).hour
    return час >= ТИХО_С or час < ТИХО_ДО


def проверить_тему(запись: dict, *, запомнить: bool = True) -> list[str]:
    """Проверяет одну тему. Возвращает новое.

    `запомнить=False` — когда ещё неизвестно, дойдёт ли новость до человека.
    Записать её в «уже сказанное» до доставки значит потерять навсегда:
    второй раз она новой не будет.
    """
    try:
        ответ = _проверить(запись)
    except Exception as exc:
        _logger.warning("Проверка «%s» сорвалась: %s", запись.get("тема"), exc)
        return []

    свежее = _новое(ответ, запись.get("известное", []))[:МАКС_НОВОСТЕЙ_ЗА_РАЗ]
    запись["проверено"] = datetime.now().isoformat(timespec="seconds")
    if запомнить:
        отметить_сказанным(запись, свежее)
    return свежее


def отметить_сказанным(запись: dict, новости: list[str]) -> None:
    """Новость дошла до человека — второй раз о ней не заговариваем."""
    известное = list(запись.get("известное", []))
    известное.extend(_нормализовать(к) for к in новости)
    запись["известное"] = известное[-ПАМЯТЬ_ОТПЕЧАТКОВ:]


def _сказать(тема: str, новости: list[str]) -> bool:
    """Голосом, через живую сессию. False — сказать было некому."""
    if not _notify:
        return False
    текст = " ".join(новости)
    доставлено = _notify(
        f"[СЛЕЖЕНИЕ] По теме «{тема}», за которой ты следишь по просьбе "
        f"пользователя, появилось новое: {текст} "
        f"Скажи это вслух одной-двумя фразами, начав с того, что следил за темой. "
        f"Не перечисляй источники и не предлагай поискать ещё."
    )
    # Прежние версии `notify` ничего не возвращали. Считать `None` отказом
    # нельзя: тогда любая новость уезжала бы в уведомление системы.
    return True if доставлено is None else bool(доставлено)


def _уведомить(тема: str, новости: list[str]) -> bool:
    """Уведомлением операционной системы — его видно, даже когда человек
    отошёл, а Джарвис в это время переподключался."""
    try:
        from actions.os_reminder import _notify_command

        команда = _notify_command(f"{тема}: {' '.join(новости)}")
        subprocess.Popen(команда, stdout=subprocess.DEVNULL,
                         stderr=subprocess.DEVNULL)
        return True
    except Exception as exc:
        _logger.warning("Уведомление по теме «%s» не показано: %s", тема, exc)
        return False


def доставить(запись: dict, новости: list[str]) -> bool:
    """Сказать и, если просили или сказать было некому, ещё и показать.

    Сессия Gemini обрывается и переподключается сама каждые несколько минут,
    и всё это время голосовой путь молча никуда не ведёт. Раньше новость в
    такой момент записывалась в «уже сказанное» и пропадала насовсем.
    """
    тема = запись["тема"]
    сказано = _сказать(тема, новости)
    показано = False

    if запись.get("уведомлять") or not сказано:
        показано = _уведомить(тема, новости)

    if (сказано or показано) and _log:
        путь = "голосом" if сказано else "уведомлением"
        _log(f"SYS: новое по теме «{тема}» — {путь}")
    return сказано or показано


def проверить_по_просьбе(тема: str = "") -> tuple[list[str], bool]:
    """Проверка по прямому вопросу. Возвращает новости и признак «есть кого».

    Отдельно от `обойти`, потому что `topics()` отдаёт КОПИИ записей: проверка
    по такой копии ничего не запоминала, и на третье «проверь» Джарвис
    зачитывал одно и то же. Здесь работа идёт с настоящими записями под
    замком, а запоминается сразу — доставка гарантирована, новость уходит
    ответом инструмента.
    """
    _загрузить()
    искомое = (тема or "").strip().lower()

    with _замок:
        if not _темы:
            return [], False
        цели = [з for з in _темы
                if not искомое or искомое in _нормализовать(з["тема"])]
        if not цели:
            return [], False

    новости: list[str] = []
    for запись in цели:
        новости.extend(проверить_тему(запись))

    with _замок:
        _записать()
    return новости, True


def обойти(сейчас: datetime | None = None) -> int:
    """Один обход всех тем. Возвращает, о скольких темах пришлось заговорить."""
    _загрузить()
    сейчас = сейчас or datetime.now()
    if тихо(сейчас):
        return 0

    with _замок:
        готовые = [з for з in _темы if _пора(з, сейчас)]

    сказано = 0
    for запись in готовые:
        новости = проверить_тему(запись, запомнить=False)
        if not новости:
            continue
        if доставить(запись, новости):
            отметить_сказанным(запись, новости)
            сказано += 1
        # Не доставили — не запоминаем: повторим в следующий обход. Иначе
        # новость, случившаяся во время переподключения, пропадала бы совсем.

    with _замок:
        _записать()
    return сказано


# ─── Фоновый поток ───────────────────────────────────────────────────────────

def _цикл() -> None:
    while not _стоп.wait(ТАКТ_СЕК):
        try:
            обойти()
        except Exception as exc:                 # слежение не роняет ассистента
            _logger.warning("Обход слежения сорвался: %s", exc, exc_info=True)


def start() -> bool:
    """Поднимает фоновый поток, если есть за чем следить. True — работает."""
    global _поток
    _загрузить()
    with _замок:
        if not _темы:
            return False
        if _поток is not None and _поток.is_alive():
            return True
        _стоп.clear()
        _поток = threading.Thread(target=_цикл, name="jarvis-watch", daemon=True)
        _поток.start()
        return True


def stop() -> None:
    global _поток
    _стоп.set()
    поток = _поток
    _поток = None
    if поток is not None and поток.is_alive():
        поток.join(timeout=2)


def reset() -> None:
    """Забывает всё, не трогая диск. Нужен тестам."""
    global _загружено, _notify, _log, _search
    stop()
    with _замок:
        _темы.clear()
        _загружено = False
    _notify = _log = _search = None
