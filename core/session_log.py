"""
Память о разговорах: «вчера мы говорили о…».

ЗАЧЕМ
    Долгосрочная память хранит ФАКТЫ: как зовут, где живёт, что любит.
    Разговор она не хранит вовсе, и каждое утро Джарвис начинал с чистого
    листа — при том, что накануне вечером обсуждали переезд, а позавчера
    искали билеты. Человек помнит об этом, ассистент нет, и это ровно та
    разница, по которой видно машину.

ПОЧЕМУ ЗАПИСЬ ДЁШЕВАЯ, А ВЫЖИМКА ЛЕНИВАЯ
    Реплики дописываются в файл дня по мере разговора: это миллисекунды и
    переживает аварийное закрытие. Выжимку делать в этот момент незачем и
    негде — на выходе из программы модель просто не успела бы ответить.

    Поэтому выжимка считается тогда, когда её впервые спрашивают, и тут же
    кладётся рядом. Один вызов модели в сутки вместо одного на каждую
    реплику — и ничего не теряется, если программу закрыли крестиком.

ЧТО С ЭТИМ ХРАНИТСЯ
    Расшифровка разговоров — не то, что стоит копить бесконечно. Файлы
    старше двух недель удаляются при первом же обращении: за две недели
    «вчера мы говорили» отвечает на любой разумный вопрос, а всё, что
    действительно важно, Джарвис к тому времени уже положил в память фактов.
"""

import json
import logging
from datetime import date, datetime, timedelta
from pathlib import Path

_logger = logging.getLogger(__name__)

ХРАНИМ_ДНЕЙ = 14

# Сколько символов расшифровки отдаём модели на выжимку. День плотного
# разговора столько и займёт; больше — это уже не «о чём говорили».
_ПРЕДЕЛ_РАСШИФРОВКИ = 12000

# Короче этого реплика не несёт смысла для выжимки: «да», «ага», «спасибо».
_МИНИМУМ_РЕПЛИКИ = 4


def _папка() -> Path:
    d = Path.home() / ".jarvis" / "sessions"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _файл(день: date) -> Path:
    return _папка() / f"{день.isoformat()}.jsonl"


def _выжимка_файл(день: date) -> Path:
    return _папка() / f"{день.isoformat()}.summary.txt"


# ─── Запись ──────────────────────────────────────────────────────────────────

def remember(кто: str, текст: str, когда: date | None = None) -> None:
    """Дописывает реплику в журнал дня. Ошибка записи не должна ничего ронять."""
    текст = (текст or "").strip()
    if len(текст) < _МИНИМУМ_РЕПЛИКИ:
        return
    try:
        строка = json.dumps({"кто": кто, "текст": текст,
                             "время": datetime.now().strftime("%H:%M")},
                            ensure_ascii=False)
        with _файл(когда or date.today()).open("a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except Exception as exc:
        _logger.debug("Реплика не записана: %s", exc)


# ─── Чтение ──────────────────────────────────────────────────────────────────

def _прочитать(день: date) -> list[dict]:
    путь = _файл(день)
    if not путь.exists():
        return []
    реплики = []
    try:
        for строка in путь.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if not строка:
                continue
            try:
                реплики.append(json.loads(строка))
            except json.JSONDecodeError:
                continue          # оборванная строка от аварийного закрытия
    except Exception as exc:
        _logger.warning("Журнал %s не прочитан: %s", путь.name, exc)
    return реплики


def дни_с_разговорами(до: date | None = None) -> list[date]:
    """Дни, в которые что-то говорили, от свежих к старым."""
    до = до or date.today()
    дни = []
    for путь in _папка().glob("*.jsonl"):
        try:
            день = date.fromisoformat(путь.stem)
        except ValueError:
            continue
        if день < до:
            дни.append(день)
    return sorted(дни, reverse=True)


def прошлый_день(до: date | None = None) -> date | None:
    """Последний день до указанного, в который был разговор.

    Именно последний, а не буквально вчера: между разговорами бывают
    выходные, и «вчера мы говорили» про день, когда компьютер не включали,
    звучало бы ложью."""
    дни = дни_с_разговорами(до)
    return дни[0] if дни else None


# ─── Уборка ──────────────────────────────────────────────────────────────────

def подчистить(сегодня: date | None = None) -> int:
    """Удаляет журналы старше ХРАНИМ_ДНЕЙ. Возвращает, сколько удалил."""
    граница = (сегодня or date.today()) - timedelta(days=ХРАНИМ_ДНЕЙ)
    удалено = 0
    for путь in list(_папка().glob("*")):
        основа = путь.name.split(".")[0]
        try:
            день = date.fromisoformat(основа)
        except ValueError:
            continue
        if день < граница:
            try:
                путь.unlink()
                удалено += 1
            except OSError as exc:
                _logger.debug("Старый журнал %s не удалён: %s", путь.name, exc)
    return удалено


# ─── Выжимка ─────────────────────────────────────────────────────────────────

def _расшифровка(реплики: list[dict]) -> str:
    строки = [f'{з.get("время", "")} {з.get("кто", "")}: {з.get("текст", "")}'
              for з in реплики]
    текст = "\n".join(строки)
    # Хвост, а не начало: конец разговора обычно важнее его завязки.
    return текст[-_ПРЕДЕЛ_РАСШИФРОВКИ:]


def выжимка(день: date, пересчитать: bool = False) -> str:
    """О чём говорили в этот день. Пустая строка — сказать нечего."""
    подчистить()

    готовая = _выжимка_файл(день)
    if готовая.exists() and not пересчитать:
        try:
            return готовая.read_text(encoding="utf-8").strip()
        except Exception as exc:
            _logger.debug("Готовая выжимка не прочитана: %s", exc)

    реплики = _прочитать(день)
    if len(реплики) < 4:
        # Два слова и «спасибо» — это не разговор, и вспоминать его утром
        # значит начинать день с пустого места.
        return ""

    from core import llm_client

    ответ = llm_client.ask(
        _расшифровка(реплики),
        система=(
            "Ниже расшифровка разговора пользователя с голосовым ассистентом. "
            "Назови ОДНИМ-ДВУМЯ предложениями, о чём говорили и что осталось "
            "незакрытым. По-русски, без markdown и списков — это читают вслух. "
            "Не пересказывай подряд и не перечисляй всё: только то, к чему "
            "человек захочет вернуться. Если говорить не о чем, ответь одним "
            "словом: нет."
        ),
        предел=200,
    ).strip()

    if not ответ or ответ.lower().rstrip(".!") == "нет":
        return ""

    try:
        готовая.write_text(ответ, encoding="utf-8")
    except Exception as exc:
        _logger.debug("Выжимка не сохранена: %s", exc)
    return ответ


def о_чём_говорили(до: date | None = None) -> tuple[str, date | None]:
    """Выжимка последнего дня с разговором и какой это был день."""
    день = прошлый_день(до)
    if день is None:
        return "", None
    return выжимка(день), день


def как_назвать(день: date, сегодня: date | None = None) -> str:
    """«Вчера», «позавчера» или дата — так, как скажет человек."""
    сегодня = сегодня or date.today()
    разница = (сегодня - день).days
    if разница <= 1:
        return "Вчера"
    if разница == 2:
        return "Позавчера"
    if разница <= 6:
        return "На днях"
    return день.strftime("%d.%m")
