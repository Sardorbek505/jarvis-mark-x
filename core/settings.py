"""
Настройки разговора: то, что подбирают на слух, а не в исходниках.

ЗАЧЕМ
    Три числа определяют, каким Джарвис кажется в разговоре: сколько тишины
    он ждёт, прежде чем счесть фразу законченной, сколько звука берёт до
    начала речи и думает ли перед ответом. Подобраны они были один раз, под
    одну комнату и один микрофон, и жили в переменных среды — то есть для
    человека не существовали вовсе.

    А жалобы на них самые частые из возможных: «перебивает» и «долго
    молчит». Это одна и та же ручка, повёрнутая не туда.

ЧЕГО ЗДЕСЬ НЕТ
    Внешнего вида HUD. Менять палитру реактора — косметическая правка в
    ui.py без единого следствия для работы, а сам HUD — наша опознаваемая
    черта, ровно по той же причине, по которой мы не берём чужое лицо с
    виземами. Настройка, которая ничего не решает, только удлиняет окно.

КАК ПРИМЕНЯЕТСЯ
    Значения читаются в момент сборки конфигурации сессии, а не при импорте.
    Поэтому новые числа вступают в силу со следующим подключением к Gemini —
    оно случается само каждые несколько минут, — а не после перезапуска.
"""

import json
import logging
import os

_logger = logging.getLogger(__name__)


class Настройка:
    """Одно значение: что это, в каких пределах и откуда берётся."""

    def __init__(self, ключ, подпись, пояснение, по_умолчанию,
                 минимум=None, максимум=None, переменная="", тип=int):
        self.ключ = ключ
        self.подпись = подпись
        self.пояснение = пояснение
        self.по_умолчанию = по_умолчанию
        self.минимум = минимум
        self.максимум = максимум
        self.переменная = переменная
        self.тип = тип

    def привести(self, значение):
        if self.тип is bool:
            if isinstance(значение, str):
                return значение.strip().lower() in ("1", "true", "да", "yes", "on")
            return bool(значение)
        try:
            число = self.тип(значение)
        except (TypeError, ValueError):
            return self.по_умолчанию
        if self.минимум is not None:
            число = max(self.минимум, число)
        if self.максимум is not None:
            число = min(self.максимум, число)
        return число


ОПИСАНИЯ = (
    Настройка(
        "vad_silence_ms", "Пауза до конца фразы, мс",
        "Сколько тишины ждать, прежде чем считать, что вы договорили. "
        "Меньше — отвечает быстрее, но чаще перебивает на раздумьях; "
        "больше — терпеливее, но с паузой перед каждым ответом.",
        220, 120, 2000, "VAD_SILENCE_MS",
    ),
    Настройка(
        "vad_prefix_ms", "Захват начала фразы, мс",
        "Сколько звука брать ДО того, как речь опознана. Если у вас "
        "проглатывается первое слово — увеличьте.",
        60, 0, 1000, "VAD_PREFIX_MS",
    ),
    Настройка(
        "thinking_budget", "Размышления перед ответом, токенов",
        "Ноль — отвечает сразу; это правильный выбор для «который час» и "
        "«включи музыку». Поднимать стоит, только если он начал путаться в "
        "многошаговых просьбах: каждый токен размышления — это задержка.",
        0, 0, 4096, "JARVIS_THINKING_BUDGET",
    ),
    Настройка(
        "show_latency", "Показывать замер задержки",
        "Строка в логе после каждого ответа: сколько прошло от конца вашей "
        "фразы до первого звука и какие инструменты сколько заняли.",
        False, переменная="JARVIS_DEBUG_UI", тип=bool,
    ),
)

_ПО_КЛЮЧУ = {о.ключ: о for о in ОПИСАНИЯ}


def _файл():
    from core.paths import get_config_path
    return get_config_path("api_keys.json", for_writing=True)


def _прочитать() -> dict:
    try:
        from core.paths import load_api_keys
        данные = load_api_keys()
        return данные if isinstance(данные, dict) else {}
    except Exception as exc:
        _logger.debug("Настройки не прочитаны: %s", exc)
        return {}


def get(ключ: str):
    """Значение настройки. Переменная среды перебивает файл: ею пользуются,
    когда надо проверить одно число на один запуск."""
    описание = _ПО_КЛЮЧУ.get(ключ)
    if описание is None:
        return None

    if описание.переменная:
        из_среды = os.getenv(описание.переменная, "").strip()
        if из_среды:
            return описание.привести(из_среды)

    данные = _прочитать()
    if ключ in данные:
        return описание.привести(данные[ключ])
    return описание.по_умолчанию


def all_settings() -> dict:
    return {о.ключ: get(о.ключ) for о in ОПИСАНИЯ}


def set(ключ: str, значение) -> bool:
    """Сохраняет настройку. False — такой настройки нет или файл не записался."""
    описание = _ПО_КЛЮЧУ.get(ключ)
    if описание is None:
        return False

    путь = _файл()
    данные = {}
    if путь.exists():
        try:
            данные = json.loads(путь.read_text(encoding="utf-8"))
        except Exception as exc:
            _logger.warning("Файл настроек не разобран, перезаписываю: %s", exc)
            данные = {}
    if not isinstance(данные, dict):
        данные = {}

    данные[ключ] = описание.привести(значение)
    try:
        from core.storage import atomic_write_json
        путь.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(путь, данные)
    except Exception as exc:
        _logger.warning("Настройка %s не сохранена: %s", ключ, exc)
        return False
    return True


def описание(ключ: str) -> Настройка | None:
    return _ПО_КЛЮЧУ.get(ключ)
