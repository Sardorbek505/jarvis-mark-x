_ПО_КЛЮЧУ = {о.ключ: о for о in ОПИСАНИЯ}


def _файл():
    from core.paths import get_config_path
    return get_config_path("api_keys.json", for_writing=True)


def _прочитать() -> dict:
    try:
        from core.paths import load_api_keys
        данные = load_api_keys()
        return данные if isinstance(данные, dict) else {}
    except Exception as exc:
        _logger.debug("Настройки не прочитаны: %s", exc)
        return {}


def get(ключ: str):
    """Значение настройки. Переменная среды перебивает файл: ею пользуются,
    когда надо проверить одно число на один запуск."""
    описание = _ПО_КЛЮЧУ.get(ключ)
    if описание is None:
        return None

    if описание.переменная:
        из_среды = os.getenv(описание.переменная, "").strip()
        if из_среды:
            return описание.привести(из_среды)

    данные = _прочитать()
    if ключ in данные:
        return описание.привести(данные[ключ])
    return описание.по_умолчанию


def all_settings() -> dict:
    return {о.ключ: get(о.ключ) for о in ОПИСАНИЯ}


def save(ключ: str, значение) -> bool:
    """Сохраняет настройку. False — такой настройки нет или файл не записался.

    Функция называлась `set` и перекрывала встроенный тип: `set()` в этом же
    модуле вызывал её, а не создавал множество. Имя, совпадающее со
    встроенным, экономит одно слово и стоит часа поисков.
    """
    описание = _ПО_КЛЮЧУ.get(ключ)
    if описание is None:
        return False

    путь = _файл()
    данные = {}
    if путь.exists():
        try:
            данные = json.loads(путь.read_text(encoding="utf-8"))
        except Exception as exc:
            _logger.warning("Файл настроек не разобран, перезаписываю: %s", exc)
            данные = {}
    if not isinstance(данные, dict):
        данные = {}

    данные[ключ] = описание.привести(значение)
    try:
        from core.storage import atomic_write_json
        путь.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(путь, данные)
    except Exception as exc:
        _logger.warning("Настройка %s не сохранена: %s", ключ, exc)
        return False
    return True


def описание(ключ: str) -> Настройка | None:
    return _ПО_КЛЮЧУ.get(ключ)


# ─── Выключенные инструменты ─────────────────────────────────────────────────
#
# 35 объявлений уходят в промпт на КАЖДОМ подключении, а подключается сессия
# сама каждые несколько минут. Человеку, у которого нет ни Spotify, ни
# Obsidian, ни игр, всё это оплачивается токенами и, что хуже, сбивает выбор:
# чем длиннее список, тем чаще модель берёт из него не тот инструмент.

_КЛЮЧ_ВЫКЛЮЧЕННЫХ = "tools_disabled"
_КЛЮЧ_ПЛАГИНОВ = "plugins_disabled"     # прежнее имя, у кого-то уже прописано

# Что выключить нельзя, и почему именно это:
#   save_to_memory / recall_memory — без них память перестаёт пополняться и
#       читаться, то есть ассистент забывает человека;
#   undo — выключенная отмена оставляет стек отмены без выхода наружу:
#       изменения сделаны, а вернуть их нечем;
#   shutdown_jarvis — единственный способ закрыть Джарвиса голосом.
НЕВЫКЛЮЧАЕМЫЕ = frozenset({
    "save_to_memory", "recall_memory", "undo", "shutdown_jarvis",
})


def disabled_tools() -> set[str]:
    данные = _прочитать()
    имена: set[str] = set()
    for ключ in (_КЛЮЧ_ВЫКЛЮЧЕННЫХ, _КЛЮЧ_ПЛАГИНОВ):
        значение = данные.get(ключ) or []
        if isinstance(значение, (list, tuple, set)):
            имена |= {str(н).strip() for н in значение if str(н).strip()}
    return имена - НЕВЫКЛЮЧАЕМЫЕ


def tool_enabled(имя: str) -> bool:
    """Загружать ли инструмент вообще.

    Не «загрузить и молчать»: модель не должна видеть в списке способность,
    которой человек её лишил, — иначе она будет её предлагать, а вызов
    упрётся в «неизвестный инструмент»."""
    return имя not in disabled_tools()


def set_disabled_tools(имена) -> bool:
    """Сохраняет список выключенных. Невыключаемые молча отбрасываются."""
    очищенные = sorted({str(н).strip() for н in (имена or []) if str(н).strip()}
                       - НЕВЫКЛЮЧАЕМЫЕ)

    путь = _файл()
    данные = {}
    if путь.exists():
        try:
            данные = json.loads(путь.read_text(encoding="utf-8"))
        except Exception as exc:
            _logger.warning("Файл настроек не разобран, перезаписываю: %s", exc)
    if not isinstance(данные, dict):
        данные = {}

    данные[_КЛЮЧ_ВЫКЛЮЧЕННЫХ] = очищенные
    # Прежний ключ больше не ведущий, но и стирать чужую настройку молча
    # нельзя: оставляем как есть, читаются оба.
    try:
        from core.storage import atomic_write_json
        путь.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(путь, данные)
    except Exception as exc:
        _logger.warning("Список выключенных не сохранён: %s", exc)
        return False
    return True
