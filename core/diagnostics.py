"""
Панель «почему он меня не слышит»: снимок голосового круга в одном месте.

ЗАЧЕМ
    Обе половины голосового круга отказывают МОЛЧА. Распознавание, которое вас
    игнорирует, и синтез, который не издаёт звука, снаружи выглядят одинаково:
    ничего не падает, ничего не мигает, окно живёт как ни в чём не бывало.

    Данные для ответа в программе уже были — причины, по которым микрофонный
    шлюз отбрасывает кадры; замер «слышит / отвечает / звучит»; состояние
    синтеза, — но лежали в трёх разных местах и утекали в лог, который надо
    уметь читать. Это не отладочная роскошь: это прибор, превращающий «не
    работает» в конкретный, отвечаемый факт.

ПОЧЕМУ СНИМОК, А НЕ ПОДПИСКА
    Панель опрашивает состояние, а не подписывается на события. Наблюдатель,
    который вмешивается в тайминг наблюдаемого, здесь бесполезен: половина
    бед голосового круга — это как раз задержки в доли секунды.

ПОЧЕМУ ЗДЕСЬ НЕТ QT
    Чтобы это можно было проверить тестом и напечатать в консоли. Окно
    рисуется в ui.py по готовым строкам.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field


@dataclass
class Строка:
    ключ: str
    значение: str
    тревога: bool = False


@dataclass
class Раздел:
    имя: str
    строки: list[Строка] = field(default_factory=list)


def _когда(отметка: float) -> str:
    if not отметка:
        return "—"
    прошло = time.time() - отметка
    if прошло < 1:
        return "только что"
    if прошло < 60:
        return f"{прошло:.0f} с назад"
    return f"{прошло / 60:.0f} мин назад"


def _достать(объект, имя, по_умолчанию=None):
    """Мягкое чтение: панель не имеет права упасть из-за поля, которого ещё
    нет. Её открывают как раз тогда, когда что-то пошло не так."""
    return getattr(объект, имя, по_умолчанию)


# ─── Разделы ─────────────────────────────────────────────────────────────────

def _слух(j) -> Раздел:
    раздел = Раздел("СЛУХ")

    прошло = _достать(j, "_gate_passed_total", 0)
    отброшено = sum((_достать(j, "_gate_totals", {}) or {}).values())
    последнее = _достать(j, "_last_pass_at", 0.0)

    молчит_давно = bool(последнее) and (time.time() - последнее) > 30
    раздел.строки.append(Строка(
        "слышит", _когда(последнее) if последнее else "ни разу за сессию",
        тревога=молчит_давно or not последнее))
    раздел.строки.append(Строка("кадров пропущено", f"{прошло}"))

    причины = _достать(j, "_gate_totals", {}) or {}
    if причины:
        главная, сколько = max(причины.items(), key=lambda п: п[1])
        раздел.строки.append(Строка("чаще всего отбрасывал", f"{главная} ({сколько})"))
    раздел.строки.append(Строка("отброшено всего", f"{отброшено}"))

    причина = _достать(j, "_last_gate_reason", "")
    if причина:
        раздел.строки.append(Строка("последний отказ", причина))

    ui = _достать(j, "ui")
    if ui is not None and _достать(ui, "muted", False):
        раздел.строки.append(Строка("микрофон", "ВЫКЛЮЧЕН (Ctrl+M)", тревога=True))
    return раздел


def _речь(j) -> Раздел:
    раздел = Раздел("РЕЧЬ")
    раздел.строки.append(Строка("говорит сейчас",
                                "да" if _достать(j, "_is_speaking", False) else "нет"))
    раздел.строки.append(Строка("ответов произнесено",
                                f"{_достать(j, '_spoken_count', 0)}"))

    сорвалось = _достать(j, "_fish_fallbacks", 0)
    раздел.строки.append(Строка(
        "Fish уступал Edge", f"{сорвалось}", тревога=сорвалось > 0))

    очередь = _достать(j, "audio_in_queue")
    if очередь is not None:
        # Не «промолчать, если не вышло»: молчащая строка неотличима от нуля,
        # а ноль в очереди — важный факт («он замолчал, потому что играть
        # нечего»). Не узнали — так и говорим.
        размер = getattr(очередь, "qsize", None)
        раздел.строки.append(Строка(
            "в очереди звука", f"{размер()}" if callable(размер) else "не узнать"))

    синтез = _достать(j, "_active_synth_tasks", 0)
    if синтез:
        раздел.строки.append(Строка("синтезируется", f"{синтез}"))
    return раздел


def _перебивание(j) -> Раздел:
    раздел = Раздел("ПЕРЕБИВАНИЕ")

    детектор = _достать(j, "_wake_detector")
    модель = _достать(детектор, "_oww_model") if детектор is not None else None
    раздел.строки.append(Строка(
        "детектор имени",
        "готов" if модель is not None else "НЕ ЗАГРУЖЕН",
        тревога=модель is None))

    aec = _достать(j, "_aec")
    if aec is None:
        раздел.строки.append(Строка("эхоподавление", "нет — порог имени строже",
                                    тревога=True))
    else:
        erle = _достать(j, "_aec_erle", 0.0) or 0.0
        раздел.строки.append(Строка("эхоподавление", f"{erle:.0f} дБ сейчас"))

    услышано = _достать(j, "_name_hits", 0)
    принято = _достать(j, "_barge_count", 0)
    раздел.строки.append(Строка("имя слышал", f"{услышано}"))
    раздел.строки.append(Строка("обрывов принято", f"{принято}"))

    отказ = _достать(j, "_last_barge_refusal", "")
    if отказ:
        # Самый частый вопрос к такой машине — «я же его позвал, почему он не
        # замолчал». Ответ должен быть виден, а не выводиться из поведения.
        раздел.строки.append(Строка("последний раз не принял", отказ, тревога=True))

    барж = _достать(j, "_barge")
    if барж is not None:
        низкий, высокий = барж.пороги
        раздел.строки.append(Строка("порог сейчас", f"{низкий:.2f} / {высокий:.2f}"))
    return раздел


def _задержка(j) -> Раздел:
    раздел = Раздел("ЗАДЕРЖКА")
    замер = _достать(j, "_latency")
    статы = _достать(замер, "_stats", {}) if замер is not None else {}

    if not статы:
        раздел.строки.append(Строка("замер", "выключен"))
        return раздел

    for ключ, подпись in (("heard", "слышит"), ("answered", "отвечает"),
                          ("played", "звучит")):
        стат = статы.get(ключ)
        if стат is None or not стат.count:
            раздел.строки.append(Строка(подпись, "—"))
            continue
        раздел.строки.append(Строка(
            подпись, f"медиана {стат.median} мс, худшая {стат.worst} мс",
            тревога=стат.median > 2500))

    имена = _достать(замер, "_tool_names", []) or []
    if имена:
        раздел.строки.append(Строка("последние инструменты", ", ".join(имена[-3:])))
    return раздел


def _связь(j) -> Раздел:
    раздел = Раздел("СВЯЗЬ")
    жива = _достать(j, "session") is not None
    раздел.строки.append(Строка("сессия", "на связи" if жива else "НЕТ",
                                тревога=not жива))
    раздел.строки.append(Строка(
        "возобновление",
        "вооружено" if _достать(j, "_resume_handle") else "ещё не выдано"))
    раздел.строки.append(Строка("переподключений",
                                f"{_достать(j, '_reconnects', 0)}"))
    return раздел


def собрать(джарвис) -> list[Раздел]:
    """Снимок всего голосового круга. Порядок — от «меня не слышат» к
    «он не отвечает»: так его и читают."""
    разделы = []
    for сборщик in (_слух, _речь, _перебивание, _задержка, _связь):
        try:
            разделы.append(сборщик(джарвис))
        except Exception as exc:
            разделы.append(Раздел(сборщик.__name__.strip("_").upper(), [
                Строка("сломалось", f"{type(exc).__name__}: {exc}"[:80], тревога=True),
            ]))
    return разделы


def текстом(разделы: list[Раздел]) -> str:
    """Тот же снимок строками — для консоли и для лога."""
    куски = []
    for раздел in разделы:
        куски.append(f"◈ {раздел.имя}")
        for строка in раздел.строки:
            метка = " !" if строка.тревога else "  "
            куски.append(f"{метка} {строка.ключ:<24} {строка.значение}")
    return "\n".join(куски)
