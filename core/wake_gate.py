"""
Сон и бодрствование: пока не позвали, в облако не уходит ничего.

ЗАЧЕМ
    Сейчас микрофон открыт всегда, и каждый громкий кадр уезжает в Gemini.
    Это значит, что разговор в комнате, телевизор и чужие слова оплачиваются
    и покидают машину — при том, что обращались не к ассистенту.

    Со шлюзом наружу не уходит ни кадра, пока не прозвучит имя. Детектор
    работает локально, на ONNX-модели, и никуда не ходит.

ПОЧЕМУ ЭТО ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ
    Модель детектора — `hey_jarvis` из открытого набора openWakeWord,
    обученная на английском «hey Jarvis». Наш человек говорит по-русски
    «Джарвис», без «hey» и с другой фонетикой: узнаваемость на этой фразе
    заведомо ниже, и насколько — зависит от голоса и микрофона.

    Для ПЕРЕБИВАНИЯ этого достаточно: не расслышал — нажми Escape. Но если
    за тем же детектором запереть весь вход, цена промаха другая: ассистент
    просто оглохнет, и человек не поймёт, почему.

    Поэтому шлюз включается настройкой, а панель диагностики (Ctrl+D) в это
    время показывает, сколько раз имя было услышано. Сначала убедиться, что
    слышит, потом запирать.

КОГДА ОН ЗАСЫПАЕТ
    По тишине. Любая речь — и своя, и чужая — продлевает бодрствование:
    разговор не должен обрываться на полуслове из-за того, что человек
    задумался на восемь секунд. Отвечающий Джарвис тоже считается разговором.
"""

import time

# Сколько тишины держит бодрствование. Больше — ассистент дольше слушает
# лишнее; меньше — приходится звать по имени в середине разговора.
ТИШИНА_ДО_СНА_СЕК = 12.0


class Шлюз:
    """Пускает ли звук наружу. Ничего не делает сам — отвечает на вопрос."""

    def __init__(self, требовать_имя: bool = False, часы=time.monotonic):
        self.требовать_имя = требовать_имя
        self._часы = часы
        self._бодр_до = 0.0
        self._разбудил = ""

    # ── Состояние ─────────────────────────────────────────────────────────

    @property
    def бодрствует(self) -> bool:
        if not self.требовать_имя:
            return True                 # шлюз выключен — слушаем как раньше
        return self._часы() < self._бодр_до

    @property
    def разбудил(self) -> str:
        """Чем разбудили в последний раз: именем, клавишей, кнопкой."""
        return self._разбудил

    def осталось(self) -> float:
        """Сколько секунд до сна. Ноль — уже спит."""
        if not self.требовать_имя:
            return float("inf")
        return max(0.0, self._бодр_до - self._часы())

    # ── Переходы ──────────────────────────────────────────────────────────

    def разбудить(self, кто: str = "имя") -> bool:
        """True — если именно этот вызов вывел из сна (а не продлил бодрость).

        Разница важна: на пробуждение положен отклик, на продление — нет.
        Иначе Джарвис звенел бы на каждую фразу разговора.
        """
        проснулся = not self.бодрствует
        self._разбудил = кто
        self._бодр_до = self._часы() + ТИШИНА_ДО_СНА_СЕК
        return проснулся

    def слышна_речь(self) -> None:
        """Речь продолжается — спать рано. Зовётся на каждый громкий кадр,
        поэтому здесь не должно быть ничего, кроме присваивания."""
        if self.бодрствует:
            self._бодр_до = self._часы() + ТИШИНА_ДО_СНА_СЕК

    def уснуть(self) -> None:
        self._бодр_до = 0.0
        self._разбудил = ""
