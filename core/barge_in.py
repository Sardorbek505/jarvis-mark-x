"""
Перебивание по ключевому слову: как решается, что Джарвиса обрывают.

ПОЧЕМУ НЕ «ЛЮБАЯ РЕЧЬ», КАК У АЛИСЫ И СИРИ
    Потому что у нас комната, а не телефон у рта. Замерено в этом же проекте:
    музыка из колонок даёт RMS 7000-14000 — ровно столько же, сколько живая
    речь, и по громкости они неразличимы. При перебивании «на любой звук»
    каждая реплика из фильма обрывала бы ответ на полуслове.

    Планка тут ещё и техническая. Чтобы обрывать по любой речи, эхоподавление
    должно работать почти идеально: любой остаток собственного голоса,
    прошедший фильтр, считался бы человеком. Слову «Джарвис» остатка мало —
    он должен ещё и прозвучать как имя.

    Платим за это тем, что «стоп» и «хватит» его не останавливают: нужно
    назвать по имени. Для ассистента, который стоит в комнате со звуком, это
    выигрыш, а не уступка. У клавиатуры остаются Ctrl+M и Escape.

ГЛАВНАЯ ЛОВУШКА, РАДИ КОТОРОЙ ЗДЕСЬ ЕСТЬ ПРАВИЛА
    Человек обращается к нему ПО ИМЕНИ: «Джарвис, какая погода?». Значит, в
    тот момент, когда Джарвис начинает отвечать, слово «Джарвис» ещё лежит в
    кольцевом буфере детектора — сказанное полторы секунды назад самим
    человеком. Без защиты ассистент обрывал бы себя на первом же слове
    КАЖДОГО ответа, и выглядело бы это как «он меня не дослушивает».

    Отсюда два правила: буфер детектора чистится в момент начала речи, и
    первые полсекунды ответа обрыв не принимается вовсе.

ВТОРАЯ ЛОВУШКА
    Джарвис может произнести слово «Джарвис» сам — в ответе о себе, при
    чтении письма, в пересказе. Пока в произносимом тексте есть это слово,
    обрывы не принимаются: иначе он замолкает от звука собственного имени.
"""

import re
import time

# Пороги детектора ключевого слова. Когда Джарвис молчит — штатные: важно
# услышать тихий голос. Когда говорит сам — выше: в микрофоне звучит он же,
# и цена ложного срабатывания здесь не «лишнее пробуждение», а оборванный
# на полуслове ответ.
ПОРОГИ_МОЛЧА = (0.38, 0.50)
ПОРОГИ_РЕЧЬ = (0.60, 0.75)

# Сколько ответа должно прозвучать, прежде чем обрыв станет возможен.
# Защита от собственного имени, сказанного человеком в самом вопросе.
РАЗГОН_СЕК = 0.6

# Сколько не принимать следующий обрыв после предыдущего: слово длиннее
# одного кадра, и детектор успевает сработать на нём дважды.
КУЛДАУН_СЕК = 1.5

_ИМЯ = re.compile(r"джарвис|jarvis", re.IGNORECASE)


class Перебивание:
    """Решает, считать ли услышанное имя обрывом. Состояния не меняет ни у
    кого, кроме себя: гасит речь вызывающий."""

    def __init__(self, часы=time.monotonic):
        self._часы = часы
        self._говорит = False
        self._текст = ""
        self._начало = 0.0
        self._прошлый_обрыв = -КУЛДАУН_СЕК

    # ── что происходит снаружи ────────────────────────────────────────────

    def заговорил(self, текст: str = "") -> None:
        self._говорит = True
        self._текст = текст or ""
        self._начало = self._часы()

    def замолчал(self) -> None:
        self._говорит = False
        self._текст = ""

    @property
    def говорит(self) -> bool:
        return self._говорит

    @property
    def пороги(self) -> tuple[float, float]:
        return ПОРОГИ_РЕЧЬ if self._говорит else ПОРОГИ_МОЛЧА

    # ── решение ───────────────────────────────────────────────────────────

    def можно_обрывать(self) -> tuple[bool, str]:
        """(обрывать ли, почему нет). Причина нужна диагностике: «он меня не
        слышит» должно превращаться в конкретный ответ, а не в догадку."""
        if not self._говорит:
            return False, "он и так молчит"
        if _ИМЯ.search(self._текст):
            return False, "он произносит это слово сам"

        сейчас = self._часы()
        if сейчас - self._начало < РАЗГОН_СЕК:
            return False, "ответ только начался"
        if сейчас - self._прошлый_обрыв < КУЛДАУН_СЕК:
            return False, "только что перебивали"
        return True, ""

    def обрыв_принят(self) -> None:
        """Зовётся после того, как речь действительно погашена."""
        self._прошлый_обрыв = self._часы()
        self.замолчал()
