"""
Мгновенное подтверждение: короткая фраза ДО того, как начнёт работать
медленный инструмент.

ЗАЧЕМ
    Поиск в сети, разбор PDF, пересказ ролика и запуск браузера занимают от
    двух до десяти секунд. Всё это время Джарвис молчит: вопрос услышан,
    инструмент работает, но снаружи это неотличимо от «завис» или «не
    расслышал». Человек повторяет вопрос — и получает вторую такую же паузу.

    Одна фраза в начале («Секунду, ищу») снимает ровно эту неопределённость.
    Стоит она полсекунды синтеза и не мешает ответу: настоящий ответ встанет
    в очередь звука следом.

ЧЕГО ЗДЕСЬ НЕТ
    Фразы не обещают результата. «Секунду, ищу» — правда в любом случае, а
    «Нашёл» до окончания поиска было бы враньём, которое через три секунды
    опровергнет сам же ответ. Ни одна фраза не говорит о сделанном.

    Быстрые инструменты молчат. Подтверждение к действию, которое отвечает за
    двести миллисекунд, — это лишний голос поверх ответа, а не забота.

ПОЧЕМУ ВАРИАНТОВ НЕСКОЛЬКО
    Одна и та же фраза, услышанная тридцатый раз за день, звучит как
    автоответчик. Варианты чередуются по кругу — по порядку, а не случайно:
    так поведение остаётся предсказуемым и проверяемым.
"""

import logging

_logger = logging.getLogger(__name__)

# Действие, не названное отдельно: инструмент медленный целиком.
_ЛЮБОЕ = "*"

# Инструмент → действие → варианты фраз.
#
# Сюда попадает только то, что стабильно занимает больше пары секунд: сеть,
# разбор документа, запуск браузера. Погода и календарь отвечают быстрее,
# чем человек успевает заметить паузу, и остаются без подтверждения.
_ФРАЗЫ: dict[str, dict[str, tuple[str, ...]]] = {
    "web_search": {
        _ЛЮБОЕ: ("Секунду, ищу.", "Минуту, посмотрю в сети."),
    },
    "morning_briefing": {
        _ЛЮБОЕ: ("Собираю сводку, сэр.", "Минуту, свожу воедино."),
    },
    "look_at_screen": {
        _ЛЮБОЕ: ("Смотрю на экран.", "Секунду, гляну на экран."),
    },
    "look_at_camera": {
        _ЛЮБОЕ: ("Смотрю в камеру.", "Секунду, включаю камеру."),
    },
    "file_processor": {
        _ЛЮБОЕ: ("Минуту, читаю файл.", "Секунду, разбираю документ."),
    },
    "youtube_video": {
        "summarize": ("Минуту, разбираю ролик.", "Секунду, читаю субтитры."),
    },
    "movie_player": {
        "play":      ("Секунду, ищу фильм.", "Минуту, поднимаю плеер."),
        "start":     ("Секунду, ищу фильм.", "Минуту, поднимаю плеер."),
        "включить":  ("Секунду, ищу фильм.", "Минуту, поднимаю плеер."),
        "запустить": ("Секунду, ищу фильм.", "Минуту, поднимаю плеер."),
    },
    "music_player": {
        "play": ("Секунду, ставлю музыку.", "Минуту, ищу запись."),
    },
    "browser": {
        # Заполняется в _варианты: интерактивные действия медленны только
        # тем, что поднимают браузер, и только в первый раз.
    },
}

# Интерактивные действия браузера. Дублировать список из actions/browser_control
# приходится осознанно: импортировать модуль действий ради множества значило бы
# тянуть за собой playwright в момент, когда решается, говорить ли полсекунды.
_БРАУЗЕР_ИНТЕРАКТИВНО = frozenset({
    "click", "type", "fill", "fill_form", "get_text", "get_url", "press",
    "scroll", "screenshot", "back", "forward", "reload",
})

_БРАУЗЕР_ФРАЗЫ = ("Секунду, поднимаю браузер.", "Минуту, открываю окно.")

# Позиция в круге вариантов — своя на каждый инструмент с действием.
_позиция: dict[str, int] = {}


def _браузер_уже_открыт() -> bool:
    """Открыт ли управляемый браузер. Ошибка импорта — значит не открыт."""
    try:
        from core import browser_session

        return browser_session.is_open()
    except Exception as exc:
        _logger.debug("Состояние браузера не выяснено: %s", exc)
        return False


def _варианты(name: str, действие: str) -> tuple[str, ...]:
    if name == "browser":
        # Клик по уже открытой странице — это доли секунды. Подтверждение
        # нужно только тому первому вызову, который запускает Chromium.
        if действие in _БРАУЗЕР_ИНТЕРАКТИВНО and not _браузер_уже_открыт():
            return _БРАУЗЕР_ФРАЗЫ
        return ()

    по_действиям = _ФРАЗЫ.get(name)
    if not по_действиям:
        return ()
    return по_действиям.get(_ЛЮБОЕ) or по_действиям.get(действие) or ()


def phrase(name: str, args: dict | None = None) -> str | None:
    """Что сказать перед вызовом `name`, или None, если говорить нечего."""
    действие = str((args or {}).get("action", "")).strip().lower()
    варианты = _варианты(str(name or ""), действие)
    if not варианты:
        return None

    ключ = f"{name}/{действие}"
    номер = _позиция.get(ключ, 0)
    _позиция[ключ] = номер + 1
    return варианты[номер % len(варианты)]


def reset() -> None:
    """Сбрасывает чередование. Нужен тестам и перезапуску сессии."""
    _позиция.clear()


# Правило для системного промпта. Модель не знает, что часть ответа уже
# прозвучала, и без этой строчки начинает свой ответ такой же фразой —
# человек слышит «Секунду, ищу» дважды подряд.
PROMPT_RULE = (
    "[ПОДТВЕРЖДЕНИЕ ПЕРЕД ДОЛГИМ ДЕЙСТВИЕМ]\n"
    "Перед медленными инструментами (поиск в сети, разбор файла, пересказ "
    "ролика, запуск браузера и плеера) короткую фразу вроде «Секунду, ищу» "
    "человек УЖЕ слышит — её произносит система, без твоего участия. "
    "Не начинай свой ответ с «сейчас посмотрю», «секунду», «минутку» и "
    "подобного: говори сразу результат."
)
