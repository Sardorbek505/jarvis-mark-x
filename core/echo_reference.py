"""
Опорный сигнал для эхоподавления — из того, что мы сами играем.

ПОЧЕМУ НЕ WASAPI LOOPBACK
    Классический путь — второй поток захвата, снимающий выход звуковой карты
    (`core/audio_capture.py`). Он нужен, когда надо вычесть ЛЮБОЙ звук
    компьютера, включая чужую музыку. Нам нужно другое и меньшее: не слышать
    СЕБЯ, пока говорим.

    А то, что мы говорим, мы знаем точно — эти самые байты только что ушли в
    устройство вывода. Отсюда опорный сигнал берётся даром: без второго
    потока, без PyAudioWPatch, без Windows и без риска, что loopback-устройства
    не найдётся. Чужую музыку тем временем приглушает ducking, и в детектор
    имени она попадает уже тише.

ПРО ВЫРАВНИВАНИЕ
    Между «отдали в устройство» и «вернулось в микрофон» лежат буферы драйвера
    и воздух — десятки миллисекунд. Подгонять их здесь не нужно: этим занят
    сам AEC (оценка задержки по GCC-PHAT, до 250 мс). Наше дело — отдавать
    опорный поток НЕПРЕРЫВНО и в том же темпе, что идёт микрофон, чтобы
    найденная задержка оставалась постоянной.

    Поэтому очередь читается строго по порядку (FIFO), а когда она пуста —
    отдаётся тишина. Брать «самый свежий кусок» вместо очередного означало бы
    рвать непрерывность на каждой паузе, и задержку пришлось бы искать заново.

ПРО ЧАСТОТУ
    Играем на 24 кГц, слушаем на 16 кГц. Опорный сигнал приводится к частоте
    микрофона сразу при записи: AEC сравнивает их семпл к семплу, и разная
    частота дала бы не эхо, а шум.
"""

import threading

import numpy as np

# Больше этого в очереди не держим. Полсекунды звука — это заведомо больше
# любой задержки тракта; всё, что старше, для вычитания уже бесполезно, а
# память занимает.
ПРЕДЕЛ_СЕМПЛОВ = 16000 // 2


class ОпорныйСигнал:
    """Очередь того, что ушло в колонки, в частоте микрофона.

    Пишется из задачи воспроизведения, читается из потока звуковой карты —
    поэтому под замком. Замок берётся на доли микросекунды: внутри только
    срезы numpy.
    """

    def __init__(self, частота_микрофона: int = 16000):
        self.частота = частота_микрофона
        self._замок = threading.Lock()
        self._очередь = np.zeros(0, dtype=np.int16)
        self.отдано_тишины = 0      # для диагностики: сколько раз нечего было вычитать

    def положить(self, pcm: bytes, частота: int) -> None:
        """Кусок, только что отданный в устройство вывода."""
        if not pcm:
            return
        данные = np.frombuffer(pcm, dtype=np.int16)
        if частота != self.частота:
            данные = _привести(данные, частота, self.частота)

        with self._замок:
            self._очередь = np.concatenate((self._очередь, данные))
            if len(self._очередь) > ПРЕДЕЛ_СЕМПЛОВ:
                self._очередь = self._очередь[-ПРЕДЕЛ_СЕМПЛОВ:]

    def взять(self, семплов: int) -> bytes:
        """Очередной кусок опорного сигнала. Тишина, если играть нечего."""
        if семплов <= 0:
            return b""
        with self._замок:
            если_есть = min(семплов, len(self._очередь))
            кусок = self._очередь[:если_есть]
            self._очередь = self._очередь[если_есть:]

        if если_есть < семплов:
            self.отдано_тишины += 1
            кусок = np.concatenate(
                (кусок, np.zeros(семплов - если_есть, dtype=np.int16)))
        return кусок.tobytes()

    def сбросить(self) -> None:
        """Забыть накопленное: начинается новая реплика, и старый хвост
        сдвинул бы выравнивание."""
        with self._замок:
            self._очередь = np.zeros(0, dtype=np.int16)

    @property
    def в_очереди(self) -> int:
        with self._замок:
            return len(self._очередь)


def _привести(данные: np.ndarray, откуда: int, куда: int) -> np.ndarray:
    """Линейная интерполяция. Для опорного сигнала этого достаточно: он идёт
    в корреляцию и в адаптивный фильтр, а не в уши."""
    сколько = int(len(данные) * куда / откуда)
    if сколько <= 0:
        return np.zeros(0, dtype=np.int16)
    места = np.linspace(0, len(данные) - 1, сколько)
    новые = np.interp(места, np.arange(len(данные)), данные)
    return np.clip(новые, -32768, 32767).astype(np.int16)
