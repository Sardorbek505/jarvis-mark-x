"""Готовые паки команд — ставятся в один клик (или голосом «установи пак
браузера»). Команда пака с app работает, только когда эта программа впереди:
«новая вкладка» в браузере — Ctrl+T, в Telegram она ничего не нажмёт.

Шаг — {"do": тип, "value": …}; типы — в core/macros.py (STEP_TYPES).
Фразы — как их говорят; {слот} — любое слово или несколько («вкладка {номер}»).
"""
from __future__ import annotations


def _k(*pairs, app: str = "") -> list[dict]:
    """(фразы через |, клавиши) → команды пака."""
    out = []
    for phrases, keys, name in pairs:
        out.append({"name": name, "phrases": phrases.split("|"), "app": app,
                    "steps": [{"do": "keys", "value": keys}]})
    return out


