"""Как расшифровка Gemini пишет имя «Джарвис».

Один список на всех: fast-path, слот-филлер и арбитраж. Стенд 16.09.2026:
«Жарвиз, сделай громче», «Джарвиз, закрой фильм» — не снимались как обращение
и уезжали в модель на 6–7 с вместо мгновенного локального исполнения.
"""

import re as _re

WAKE_NAME_VARIANTS = (
    "джарвис", "джарвиз", "джарвист", "джарвес", "джарвиc",
    "жарвис", "жарвиз", "жарвест", "жарвес",
    "джервис", "джервиз", "жервис",
    "jarvis", "djarvis",
)

# Для regex: (?:джарвис|джарвиз|…) — длинные раньше коротких, чтобы «джарвист»
# не обрезался до «джарвис» + «т».
WAKE_NAME_PATTERN = "(?:" + "|".join(sorted(WAKE_NAME_VARIANTS, key=len, reverse=True)) + ")"


_VOCATIVE_RE = _re.compile(r"^\s*([А-Яа-яЁёA-Za-z\-]{2,12})\s*[,!]\s+(.+)$", _re.S)


def strip_vocative(text: str, wake_spotted: bool) -> str:
    """Снимает искажённое имя в начале расшифровки: «Чарли, который час».

    Строковая похожесть тут не работает («сервис» ближе к «джарвис», чем
    «чарльз»), поэтому правило позиционное: детектор подтвердил слово, а
    фраза начинается с ОДНОГО слова и запятой — это и есть имя, как его
    услышала расшифровка. Известные варианты снимаются и без запятой.
    """
    if not text:
        return text
    if not wake_spotted:
        return text
    m = _VOCATIVE_RE.match(text)
    if not m:
        return text
    return m.group(2).strip()
