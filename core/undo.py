"""
Общий стек отмены для действий, меняющих состояние машины.

ЗАЧЕМ
    Голосовой ассистент ослышивается. Когда это происходит, «прошу прощения»
    не помогает: файл уже в другой папке, а яркость уже на десяти процентах.
    До этого модуля единственным способом вернуть всё назад были руки.

    Обратная крайность — спрашивать «вы уверены?» перед каждым действием —
    хуже: каждый вопрос это лишний круг до модели и обратно, а ассистент,
    переспрашивающий про громкость, быстро перестаёт быть нужным.

    Поэтому: делаем сразу, помним, как откатить, и ждём слова «отмени».
    Подтверждение (core/confirm.py) остаётся только для того, что откатить
    нельзя в принципе — выключения и перезагрузки.

КАК ДЕЙСТВИЕ ПОДКЛЮЧАЕТСЯ
    Действию не нужно знать ничего о внутренностях этого файла. Оно снимает
    состояние «до» и отдаёт функцию без аргументов:

        from core.undo import push_undo
        old = _volume_get()
        _volume_set(new)
        push_undo(f"громкость → {new}%", lambda: _volume_set(old))

    Только само действие знает, что обратное к «перемести A в B» — это
    «перемести B в A». Централизовать можно стек, порядок и потокобезопасность,
    но не смысл отката.

ЦЕНА
    Запись — это append в список под локом, микросекунды. Ничего отсюда не
    выполняется, пока человек не попросит. Этот модуль не может замедлить
    ассистента.
"""

from __future__ import annotations

import logging
import threading
import time
from collections.abc import Callable
from dataclasses import dataclass, field

logger = logging.getLogger("jarvis.undo")

# Сколько обратимых операций держим. Десять — это примерно «текущий разговор»:
# достаточно далеко, чтобы поймать ошибку, замеченную через пару команд, и
# достаточно коротко, чтобы замыкание со старым содержимым файла не копилось
# в памяти.
MAX_DEPTH = 10

# Файлы крупнее этого не стоит держать в памяти ради отмены перезаписи.
# Действие, которое хочет откатить запись, должно само свериться с лимитом.
MAX_SNAPSHOT_BYTES = 1 * 1024 * 1024


@dataclass
class _Entry:
    label: str                       # человеческая фраза, её произносят вслух
    undo:  Callable[[], str | None]  # возвращает короткое уточнение или None
    at:    float = field(default_factory=time.time)


_stack: list[_Entry] = []
_lock = threading.Lock()


def push_undo(label: str, undo_fn: Callable[[], str | None]) -> None:
    """Запоминает, что произошло `label` и что `undo_fn()` это обращает.

    Зовётся из обработчиков действий, которые живут в потоках executor'а —
    отсюда лок. Никогда не бросает исключений: сорвавшаяся регистрация отмены
    не должна ронять действие, которое уже успешно выполнилось."""
    if not callable(undo_fn):
        return
    try:
        with _lock:
            _stack.append(_Entry(label=str(label)[:120], undo=undo_fn))
            # Выбрасываем самое старое, а не отказываем новому: отменяют
            # обычно недавнее.
            while len(_stack) > MAX_DEPTH:
                _stack.pop(0)
    except Exception as exc:                       # pragma: no cover
        logger.warning("Не удалось записать отмену «%s»: %s", label, exc)


def can_undo() -> bool:
    with _lock:
        return bool(_stack)


def peek() -> str:
    """Подпись операции, которую отменит `undo_last()`, либо пустая строка."""
    with _lock:
        return _stack[-1].label if _stack else ""


def history() -> list[str]:
    """Самое свежее первым — для режима list у инструмента `undo`."""
    with _lock:
        return [e.label for e in reversed(_stack)]


def undo_last() -> str:
    """Обращает последнюю обратимую операцию.

    Запись снимается со стека ДО выполнения: падающий откат нельзя
    бесконечно повторять против мира, который уже ушёл вперёд — файла,
    который пытаются вернуть, может уже не быть."""
    with _lock:
        entry = _stack.pop() if _stack else None

    if entry is None:
        return ("Отменять нечего, сэр. Я веду учёт только того, что менял сам: "
                "файлы, которые перемещал или переписывал, и настройки, которые крутил.")

    try:
        detail = entry.undo() or ""
    except Exception as exc:
        logger.warning("Откат «%s» не удался: %s", entry.label, exc)
        return f"Не удалось отменить «{entry.label}»: {exc}"

    return f"Отменено: {entry.label}." + (f" {detail}" if detail else "")


def clear() -> None:
    """Забыть стек. Зовётся при выходе, чтобы замыкания со старым содержимым
    файлов не пережили сессию."""
    with _lock:
        _stack.clear()
